-- 00272 — سياسات الاحتفاظ بالبيانات النصية (١): السياسات، الطلبات الآلية، أقفال السلامة، التأكيد، الحذف بدفعات
-- المبدأ: النظام ينشئ «طلب حذف» تلقائياً عند انقضاء مدة الاحتفاظ ويبلّغ التطوير المركزية —
-- ولا يُحذف صف واحد إلا بعد (تصدير مُثبَت إن كان مطلوباً) + تأكيد يدوي من IT. أقفال السلامة ثابتة لا تُعطَّل من الإعدادات.
-- الأنواع في هذه الجولة: البصمات الخام من الأجهزة، ونقاط GPS التفصيلية. كلها معطّلة افتراضياً.

