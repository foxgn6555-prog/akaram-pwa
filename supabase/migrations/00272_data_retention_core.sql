-- ─────────────── ⑦ الجدولة اليومية (الفحص فقط — لا حذف آلي) ───────────────
do $$
begin
  begin
    create extension if not exists pg_cron;
  exception when others then
    raise notice 'pg_cron غير متاح — الفحص الآلي يتطلب تفعيله؛ زر «فحص الآن» في صفحة IT يعمل بلا جدولة';
    return;
  end;
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.unschedule(jobid) from cron.job where jobname = 'data_retention_scan_daily';
    perform cron.schedule('data_retention_scan_daily', '0 1 * * *', $job$ select app.data_retention_scan() $job$);   -- 04:00 بغداد
  end if;
end $$;
