-- ─────────────── ② الجداول ───────────────
create table if not exists public.data_retention_policies (
  data_key         text primary key,
  enabled          boolean not null default false,
  retention_months int not null check (retention_months between 1 and 120),
  export_required  boolean not null default false,
  updated_by       uuid references auth.users(id) on delete set null,
  updated_at       timestamptz not null default now()
);
create table if not exists public.data_retention_requests (
  id               uuid primary key default gen_random_uuid(),
  data_key         text not null,
  cutoff           timestamptz not null,                -- تُحذف الصفوف الأقدم من هذا الوقت فقط
  status           text not null default 'pending' check (status in ('pending','exported','confirmed','deleting','done','cancelled')),
  rows_total       bigint not null default 0,           -- أقدم من المهلة
  rows_locked      bigint not null default 0,           -- منها محمية بقفل سلامة
  rows_exported    bigint,
  export_sha256    text,
  export_label     text,
  exported_by      uuid references auth.users(id) on delete set null,
  exported_at      timestamptz,
  confirmed_by     uuid references auth.users(id) on delete set null,
  confirmed_at     timestamptz,
  rows_deleted     bigint not null default 0,
  finished_at      timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create unique index if not exists data_retention_requests_open_idx on public.data_retention_requests (data_key) where status in ('pending','exported','confirmed','deleting');
create table if not exists public.data_retention_events (
  id          bigint generated by default as identity primary key,
  request_id  uuid references public.data_retention_requests(id) on delete cascade,
  data_key    text,
  action      text not null,
  details     jsonb,
  actor_id    uuid,
  actor_name  text,
  created_at  timestamptz not null default now()
);
alter table public.data_retention_policies enable row level security;
alter table public.data_retention_requests enable row level security;
alter table public.data_retention_events   enable row level security;
drop policy if exists "data_retention_policies: it read" on public.data_retention_policies;
create policy "data_retention_policies: it read" on public.data_retention_policies for select to authenticated using (app.has_role(array['it_admin','super_admin']));
drop policy if exists "data_retention_requests: it read" on public.data_retention_requests;
create policy "data_retention_requests: it read" on public.data_retention_requests for select to authenticated using (app.has_role(array['it_admin','super_admin']));
drop policy if exists "data_retention_events: it read" on public.data_retention_events;
create policy "data_retention_events: it read" on public.data_retention_events for select to authenticated using (app.has_role(array['it_admin','super_admin']));

create or replace function app.data_retention_log(p_req uuid, p_key text, p_action text, p_details jsonb) returns void
language plpgsql security definer set search_path = public, app as $$
begin
  insert into public.data_retention_events (request_id, data_key, action, details, actor_id, actor_name)
  values (p_req, p_key, p_action, p_details, auth.uid(), case when auth.uid() is null then 'النظام' else app.user_display_name(auth.uid()) end);
end$$;

-- ─────────────── ③ العدّ والحذف لكل نوع (أقفال السلامة هنا، ثابتة) ───────────────
-- يعيد (الإجمالي الأقدم من المهلة، المحمي منها)
create or replace function app.data_retention_count(p_key text, p_cutoff timestamptz, out total bigint, out locked bigint)
language plpgsql stable security definer set search_path = public, app as $$
begin
  if p_key = 'biometric_raw_punches' then
    select count(*),
           count(*) filter (where not exists (
             select 1 from public.payrolls pr
             where pr.period_month = date_trunc('month', (b.punched_at at time zone 'Asia/Baghdad'))::date
               and pr.status in ('approved','paid')))
      into total, locked
      from public.biometric_punches b where b.punched_at < p_cutoff;
  elsif p_key = 'gps_position_history' then
    select count(*), count(*) filter (where app.data_retention_gps_locked(h.device_id, h.fix_time))
      into total, locked
      from public.gps_device_position_history h where h.fix_time < p_cutoff;
  else
    raise exception 'RETENTION_UNKNOWN_KEY: %', p_key;
  end if;
end$$;

-- نقطة GPS محمية إذا وقعت ضمن رحلة (خروج من الكراج) عليها تحقيق غير محلول
create or replace function app.data_retention_gps_locked(p_device uuid, p_at timestamptz) returns boolean
language sql stable security definer set search_path = public, app as $$
  select exists (
    select 1
    from public.gps_vehicle_bindings vb
    join public.garage_departures d on d.vehicle_id = vb.garage_vehicle_id
    join public.gps_trip_investigations ti on ti.departure_id = d.id and ti.status <> 'resolved'
    where vb.device_id = p_device
      and p_at >= d.departed_at and p_at <= coalesce(d.returned_at, now()))
$$;

-- حذف دفعة واحدة من الصفوف غير المحمية؛ يعيد عدد المحذوف
create or replace function app.data_retention_delete_some(p_key text, p_cutoff timestamptz, p_limit int) returns bigint
language plpgsql security definer set search_path = public, app as $$
declare n bigint := 0;
begin
  if p_key = 'biometric_raw_punches' then
    with victims as (
      select b.id from public.biometric_punches b
      where b.punched_at < p_cutoff
        and exists (select 1 from public.payrolls pr
                    where pr.period_month = date_trunc('month', (b.punched_at at time zone 'Asia/Baghdad'))::date
                      and pr.status in ('approved','paid'))
      order by b.punched_at limit p_limit)
    delete from public.biometric_punches b using victims v where b.id = v.id;
    get diagnostics n = row_count;
  elsif p_key = 'gps_position_history' then
    with victims as (
      select h.id from public.gps_device_position_history h
      where h.fix_time < p_cutoff and not app.data_retention_gps_locked(h.device_id, h.fix_time)
      order by h.fix_time limit p_limit)
    delete from public.gps_device_position_history h using victims v where h.id = v.id;
    get diagnostics n = row_count;
  else
    raise exception 'RETENTION_UNKNOWN_KEY: %', p_key;
  end if;
  return n;
end$$;

-- ─────────────── ④ الإعدادات (IT) ───────────────
create or replace function app.data_retention_request_json(r public.data_retention_requests) returns jsonb
language sql stable security definer set search_path = public, app as $$
  select jsonb_build_object(
    'id', r.id, 'data_key', r.data_key, 'label', (select c.label from app.data_retention_catalog() c where c.data_key = r.data_key),
    'cutoff', r.cutoff, 'status', r.status,
    'rows_total', r.rows_total, 'rows_locked', r.rows_locked, 'rows_deletable', r.rows_total - r.rows_locked,
    'export_required', coalesce((select p.export_required from public.data_retention_policies p where p.data_key = r.data_key), false),
    'rows_exported', r.rows_exported, 'export_sha256', r.export_sha256, 'export_label', r.export_label,
    'exported_by_name', app.user_display_name(r.exported_by), 'exported_at', r.exported_at,
    'confirmed_by_name', app.user_display_name(r.confirmed_by), 'confirmed_at', r.confirmed_at,
    'rows_deleted', r.rows_deleted, 'finished_at', r.finished_at, 'created_at', r.created_at, 'updated_at', r.updated_at,
    'can_export', r.status = 'pending',
    'can_confirm', (r.status = 'exported') or (r.status = 'pending' and not coalesce((select p.export_required from public.data_retention_policies p where p.data_key = r.data_key), false)),
    'events', coalesce((select jsonb_agg(jsonb_build_object('action', e.action, 'details', e.details, 'actor_name', e.actor_name, 'at', e.created_at) order by e.id)
                        from public.data_retention_events e where e.request_id = r.id), '[]'::jsonb))
$$;

create or replace function public.data_retention_settings_get() returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
begin
  perform app.require_it();
  return coalesce((select jsonb_agg(jsonb_build_object(
      'data_key', c.data_key, 'label', c.label, 'description', c.description, 'safety_lock', c.safety_lock,
      'enabled', coalesce(p.enabled, false),
      'retention_months', coalesce(p.retention_months, c.default_months),
      'export_required', coalesce(p.export_required, c.default_export_required),
      'updated_at', p.updated_at, 'updated_by_name', app.user_display_name(p.updated_by),
      'open_request', (select app.data_retention_request_json(r) from public.data_retention_requests r
                        where r.data_key = c.data_key and r.status in ('pending','exported','confirmed','deleting') limit 1)
    ) order by c.data_key)
    from app.data_retention_catalog() c left join public.data_retention_policies p on p.data_key = c.data_key), '[]'::jsonb);
end$$;

create or replace function public.data_retention_policy_set(p_key text, p_enabled boolean, p_months int, p_export_required boolean) returns jsonb
language plpgsql security definer set search_path = public, app as $$
begin
  perform app.require_it();
  if not exists (select 1 from app.data_retention_catalog() c where c.data_key = p_key) then raise exception 'RETENTION_UNKNOWN_KEY: %', p_key; end if;
  if p_months is null or p_months < 1 or p_months > 120 then raise exception 'RETENTION_INPUT_INVALID: months'; end if;
  insert into public.data_retention_policies (data_key, enabled, retention_months, export_required, updated_by, updated_at)
  values (p_key, coalesce(p_enabled, false), p_months, coalesce(p_export_required, false), auth.uid(), now())
  on conflict (data_key) do update set enabled = excluded.enabled, retention_months = excluded.retention_months,
    export_required = excluded.export_required, updated_by = excluded.updated_by, updated_at = now();
  perform app.data_retention_log(null, p_key, 'policy_set', jsonb_build_object('enabled', p_enabled, 'months', p_months, 'export_required', p_export_required));
  -- إيقاف السياسة يلغي طلبها المفتوح غير المؤكَّد (ما بدأ حذفه يُكمل أو يُلغى يدوياً)
  if not coalesce(p_enabled, false) then
    update public.data_retention_requests set status = 'cancelled', updated_at = now(), finished_at = now()
    where data_key = p_key and status in ('pending','exported');
  end if;
  return public.data_retention_settings_get();
end$$;

-- ─────────────── ⑤ الفحص الآلي: إنشاء/تحديث الطلبات + التبليغ ───────────────
create or replace function app.data_retention_scan() returns int
language plpgsql security definer set search_path = public, app as $$
declare p record; c record; cut timestamptz; r public.data_retention_requests; created int := 0;
begin
  for p in select * from public.data_retention_policies where enabled loop
    cut := date_trunc('day', now() - make_interval(months => p.retention_months));
    select * into r from public.data_retention_requests where data_key = p.data_key and status in ('pending','exported','confirmed','deleting') limit 1;
    if r.id is null then
      select * into c from app.data_retention_count(p.data_key, cut);
      if c.total - c.locked > 0 then
        insert into public.data_retention_requests (data_key, cutoff, rows_total, rows_locked) values (p.data_key, cut, c.total, c.locked) returning * into r;
        perform app.data_retention_log(r.id, p.data_key, 'request_created', jsonb_build_object('cutoff', cut, 'rows_total', c.total, 'rows_locked', c.locked, 'months', p.retention_months));
        perform app.notify_by_role(array['it_admin','super_admin'],
          'طلب حذف بيانات بانتظار قراركم: ' || (select cc.label from app.data_retention_catalog() cc where cc.data_key = p.data_key),
          format('انقضت مدة الاحتفاظ (%s أشهر). %s صفاً أقدم من %s قابلة للحذف%s. لن يُحذف شيء قبل %sالتأكيد من التطوير المركزية.',
                 p.retention_months, c.total - c.locked, to_char(cut at time zone 'Asia/Baghdad', 'YYYY-MM-DD'),
                 case when c.locked > 0 then format(' (و%s محمية بقفل السلامة)', c.locked) else '' end,
                 case when p.export_required then 'التصدير و' else '' end),
          'warning', '/it/data-retention');
        created := created + 1;
      end if;
    elsif r.status = 'pending' then
      -- الطلب لم يُصدَّر بعد: تتقدم المهلة وتُحدَّث الأعداد
      select * into c from app.data_retention_count(p.data_key, cut);
      update public.data_retention_requests set cutoff = cut, rows_total = c.total, rows_locked = c.locked, updated_at = now() where id = r.id;
    end if;
  end loop;
  return created;
end$$;

create or replace function public.data_retention_scan_now() returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare n int;
begin
  perform app.require_it();
  n := app.data_retention_scan();
  return jsonb_build_object('created', n, 'settings', public.data_retention_settings_get());
end$$;

-- ─────────────── ⑥ دورة الطلب: تصدير مُثبَت → تأكيد → حذف بدفعات ───────────────
create or replace function public.data_retention_requests_list(p_limit int default 50) returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
begin
  perform app.require_it();
  return coalesce((select jsonb_agg(app.data_retention_request_json(r) order by (r.status in ('pending','exported','confirmed','deleting')) desc, r.created_at desc)
                   from (select * from public.data_retention_requests order by created_at desc limit greatest(1, least(p_limit, 200))) r), '[]'::jsonb);
end$$;

-- إثبات التصدير: العدد المصدَّر يجب أن يساوي القابل للحذف الآن بالضبط
create or replace function public.data_retention_export_recorded(p_request uuid, p_rows bigint, p_sha256 text, p_label text) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare r public.data_retention_requests; c record;
begin
  perform app.require_it();
  select * into r from public.data_retention_requests where id = p_request for update;
  if r.id is null then raise exception 'RETENTION_NOT_FOUND'; end if;
  if r.status <> 'pending' then raise exception 'RETENTION_BAD_STATE: %', r.status; end if;
  if p_sha256 !~ '^[0-9a-f]{64}$' then raise exception 'RETENTION_INPUT_INVALID: sha256'; end if;
  if length(trim(coalesce(p_label, ''))) = 0 then raise exception 'RETENTION_INPUT_INVALID: label'; end if;
  select * into c from app.data_retention_count(r.data_key, r.cutoff);
  if p_rows is distinct from (c.total - c.locked) then raise exception 'RETENTION_EXPORT_COUNT_MISMATCH: exported % expected %', p_rows, c.total - c.locked; end if;
  update public.data_retention_requests set status = 'exported', rows_total = c.total, rows_locked = c.locked, rows_exported = p_rows,
    export_sha256 = p_sha256, export_label = trim(p_label), exported_by = auth.uid(), exported_at = now(), updated_at = now() where id = r.id returning * into r;
  perform app.data_retention_log(r.id, r.data_key, 'exported', jsonb_build_object('rows', p_rows, 'sha256', p_sha256, 'label', trim(p_label)));
  return app.data_retention_request_json(r);
end$$;

create or replace function public.data_retention_confirm(p_request uuid) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare r public.data_retention_requests; need_export boolean; c record;
begin
  perform app.require_it();
  select * into r from public.data_retention_requests where id = p_request for update;
  if r.id is null then raise exception 'RETENTION_NOT_FOUND'; end if;
  need_export := coalesce((select p.export_required from public.data_retention_policies p where p.data_key = r.data_key), false);
  if r.status = 'pending' and need_export then raise exception 'RETENTION_EXPORT_REQUIRED'; end if;
  if r.status not in ('pending','exported') then raise exception 'RETENTION_BAD_STATE: %', r.status; end if;
  if not coalesce((select p.enabled from public.data_retention_policies p where p.data_key = r.data_key), false) then raise exception 'RETENTION_POLICY_DISABLED'; end if;
  if r.status = 'exported' then
    -- إثبات التصدير ما زال مطابقاً (لم تدخل/تخرج صفوف منذ التصدير)
    select * into c from app.data_retention_count(r.data_key, r.cutoff);
    if r.rows_exported is distinct from (c.total - c.locked) then raise exception 'RETENTION_EXPORT_STALE: exported % now %', r.rows_exported, c.total - c.locked; end if;
  end if;
  update public.data_retention_requests set status = 'confirmed', confirmed_by = auth.uid(), confirmed_at = now(), updated_at = now() where id = r.id returning * into r;
  perform app.data_retention_log(r.id, r.data_key, 'confirmed', jsonb_build_object('rows_deletable', r.rows_total - r.rows_locked));
  return app.data_retention_request_json(r);
end$$;

-- دفعة حذف (تُستدعى تكراراً من الواجهة؛ قابلة للإيقاف بين الدفعات)
create or replace function public.data_retention_delete_batch(p_request uuid, p_limit int default 5000) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare r public.data_retention_requests; n bigint; c record;
begin
  perform app.require_it();
  select * into r from public.data_retention_requests where id = p_request for update;
  if r.id is null then raise exception 'RETENTION_NOT_FOUND'; end if;
  if r.status not in ('confirmed','deleting') then raise exception 'RETENTION_BAD_STATE: %', r.status; end if;
  n := app.data_retention_delete_some(r.data_key, r.cutoff, greatest(1, least(coalesce(p_limit, 5000), 20000)));
  select * into c from app.data_retention_count(r.data_key, r.cutoff);
  update public.data_retention_requests set rows_deleted = rows_deleted + n, status = case when c.total - c.locked = 0 then 'done' else 'deleting' end,
    finished_at = case when c.total - c.locked = 0 then now() else null end, updated_at = now() where id = r.id returning * into r;
  if r.status = 'done' then perform app.data_retention_log(r.id, r.data_key, 'done', jsonb_build_object('rows_deleted', r.rows_deleted, 'rows_locked_kept', c.locked));
  elsif n > 0 then perform app.data_retention_log(r.id, r.data_key, 'batch', jsonb_build_object('rows', n)); end if;
  return app.data_retention_request_json(r);
end$$;

create or replace function public.data_retention_cancel(p_request uuid) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare r public.data_retention_requests;
begin
  perform app.require_it();
  select * into r from public.data_retention_requests where id = p_request for update;
  if r.id is null then raise exception 'RETENTION_NOT_FOUND'; end if;
  if r.status not in ('pending','exported','confirmed','deleting') then raise exception 'RETENTION_BAD_STATE: %', r.status; end if;
  update public.data_retention_requests set status = 'cancelled', finished_at = now(), updated_at = now() where id = r.id returning * into r;
  perform app.data_retention_log(r.id, r.data_key, 'cancelled', jsonb_build_object('rows_deleted_so_far', r.rows_deleted));
  return app.data_retention_request_json(r);
end$$;

