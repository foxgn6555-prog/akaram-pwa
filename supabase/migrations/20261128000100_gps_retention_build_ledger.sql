-- العطل الذي يُصلحه هذا الترحيل:
--   `app.gps_history_daily_purge()` في 00328 كان ينفّذ
--        truncate table public.gps_device_position_history;
--   **كل ليلة 21:00 UTC بلا أي شرط عمر ولا أي تحقّق من أن اليوم قد بُني**.
--   ولا يوجد أي استخراج آلي يقابله ⇒ كل يوم لا يضغط فيه أحد «استخراج» يدوياً تُفقد نقاطه نهائياً.
--   الدليل الحيّ على الإنتاج (2026-11-24): أقدم نقطة في الجدول 20:59:45 UTC أي **قبل** لحظة
--   التفريغ (21:00) بدقيقة وربع ⇒ نقاط تصل متأخرةً تُكتب بعد الحذف. الحذف الشامل يفقد بيانات
--   حتى لو بُني اليوم، لأن النقاط المتأخرة لم تكن موجودة لحظة البناء.
--
-- القاعدة الجديدة (قرار المالك 2026-11-24):
--   ① النقاط الخام تبقى **٤٨ ساعة** ثم تُحذف — **ولا تُحذف نقطة ليوم لم يُثبت بناؤه**.
--   ② الزيارات (`map_visits`) تبقى **٣٠ يوماً** ومحميّة بـ«إثبات تصدير» قبل أي حذف
--      (لا تُحذف من هنا؛ تُدار عبر كتالوج الاحتفاظ — أُضيفت في ⑨ وأُفعِّلت سياستها في الجولة ④).
--   ③ البناء الآلي يغطّي كل زون × كل يوم بغدادي متاح ويسجّل النتيجة صراحةً
--      (built / empty / failed / skipped) — والسجل هو **الإذن الوحيد للحذف**.
--
-- التراجع (غير مُستحسن — يعيد عطل فقدان البيانات):
--   drop function if exists public.gps_visits_build_run(int);
--   drop function if exists app.gps_visits_build_scan(int);
--   drop function if exists public.map_visit_build_logged(uuid,date,uuid,int,int);
--   drop function if exists app.gps_visit_build_fail(uuid,date,uuid,bigint,timestamptz,timestamptz,text);
--   drop function if exists app.gps_day_is_certified(date);
--   drop table    if exists public.gps_visit_builds;
--   ثم إعادة تطبيق جسم 00328 لاسترجاع التفريغ الشامل.
-- ═══════════════════════════════════════════════════════════════════════════════════════

-- ───────────────────────────────────────────────────────────────────────────────────────
-- ① سجل البناء: صفّ واحد لكل (زون × يوم بغدادي)
--    الحالة 'built' أو 'empty' هي **الشهادة**. بدونها لا تُحذف نقطة واحدة من ذلك اليوم.
-- ───────────────────────────────────────────────────────────────────────────────────────
create table if not exists public.gps_visit_builds (
  id              bigint generated by default as identity primary key,
  zone_id         uuid not null references public.map_zones(id) on delete cascade,
  day             date not null,
  status          text not null check (status in ('built', 'empty', 'failed', 'skipped')),
  trigger_kind    text not null default 'manual' check (trigger_kind in ('manual', 'nightly', 'recovery')),
  visits_created  int,
  visits_merged   int,
  places_scanned  int,
  skipped_visits  int,
  points_in_day   bigint,
  points_at_build timestamptz,   -- أحدث نقطة شملها البناء — الأساس لإثبات الاكتمال
  started_at      timestamptz not null default now(),
  finished_at     timestamptz,
  duration_ms     int,
  error           text,
  actor_id        uuid,
  actor_name      text,
  created_at      timestamptz not null default now()
);

-- صفّ واحد لكل (زون، يوم). لا آلية واحدة هنا: البناء للزون كاملاً يجعل الشهادة قاطعة.
create unique index if not exists gps_visit_builds_uk on public.gps_visit_builds (zone_id, day);
create index if not exists gps_visit_builds_day_idx on public.gps_visit_builds (day desc);
create index if not exists gps_visit_builds_status_idx on public.gps_visit_builds (status, day);

comment on table  public.gps_visit_builds is
  'سجل بناء الزيارات لكل (زون × يوم). built/empty شرط إلزامي قبل حذف نقاط اليوم — لا حذف على الثقة.';
comment on column public.gps_visit_builds.status is
  'built = بُني ونجح · empty = لا نقاط لذلك اليوم · failed = رمى المحرّك خطأ · skipped = تجاوز متعمّد';
comment on column public.gps_visit_builds.points_at_build is
  'أحدث fix_time داخل اليوم لحظة البناء — إن ظهرت نقاط أحدث لاحقاً فالبناء ناقص ويُعاد';

alter table public.gps_visit_builds enable row level security;

