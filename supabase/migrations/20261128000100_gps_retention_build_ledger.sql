create or replace function app.gps_history_daily_purge(p_force boolean default false) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  s          public.gps_history_purge_settings;
  v_cutoff   timestamptz;
  v_rows     bigint := 0;
  v_kept     bigint := 0;
  v_before   bigint;
  v_after    bigint;
  v_skipped  jsonb := '[]'::jsonb;
  v_total    bigint;
  dd         date;
  v_n        bigint;
begin
  select * into s from public.gps_history_purge_settings where id = 1 for update;
  if not s.enabled and not p_force then
    return jsonb_build_object('skipped', true, 'reason', 'disabled');
  end if;

  v_cutoff := now() - make_interval(hours => s.keep_hours);
  v_before := pg_total_relation_size('public.gps_device_position_history'::regclass);
  select count(*) into v_total from public.gps_device_position_history;

  -- الأيام البغدادية التي لها نقاط أقدم من الحد
  for dd in
    select distinct app.map_baghdad_day(h.fix_time)
      from public.gps_device_position_history h
     where h.fix_time < v_cutoff
  loop
    if app.gps_day_is_certified(dd) then
      delete from public.gps_device_position_history h
       where h.fix_time < v_cutoff
         and app.map_baghdad_day(h.fix_time) = dd;
      get diagnostics v_n = row_count;
      v_rows := v_rows + v_n;
    else
      select count(*) into v_n
        from public.gps_device_position_history h
       where h.fix_time < v_cutoff
         and app.map_baghdad_day(h.fix_time) = dd;
      v_kept := v_kept + v_n;
      v_skipped := v_skipped || jsonb_build_object('day', dd, 'rows', v_n);
    end if;
  end loop;

  v_after := pg_total_relation_size('public.gps_device_position_history'::regclass);

  update public.gps_history_purge_settings set
    last_run_at = now(), last_rows = v_rows, last_skipped_rows = v_kept,
    last_skipped = v_skipped,
    last_bytes_before = v_before, last_bytes_after = v_after,
    last_error = null, runs_count = runs_count + 1
  where id = 1;

  perform app.data_retention_log(null, 'gps_position_history', 'aged_purge',
    jsonb_build_object('rows_purged', v_rows, 'rows_kept', v_kept, 'keep_hours', s.keep_hours,
                       'cutoff', v_cutoff, 'skipped_days', v_skipped, 'table_rows', v_total,
                       'bytes_before', v_before, 'bytes_after', v_after, 'forced', p_force));

  -- أي يوم مُتجاوَز = خطر فقدان قادم ⇒ تنبيه فوري
  if jsonb_array_length(v_skipped) > 0 then
    perform app.notify_by_role(array['it_admin', 'super_admin', 'ops_room_manager'],
      'التفريغ تجاوز ' || jsonb_array_length(v_skipped) || ' يوماً بلا شهادة بناء',
      v_kept || ' نقطة بقيت في الجدول لأن زيارات يومها لم تُبنَ بعد. شغّل البناء المتأخر ثم يُحذف تلقائياً في التشغيل القادم.',
      'warning', '/it/data-retention');
  end if;

  return jsonb_build_object('ok', true, 'rows_purged', v_rows, 'rows_kept', v_kept,
    'skipped_days', v_skipped, 'keep_hours', s.keep_hours,
    'bytes_before', v_before, 'bytes_after', v_after);
exception when others then
  update public.gps_history_purge_settings set last_error = sqlerrm where id = 1;
  perform app.data_retention_log(null, 'gps_position_history', 'aged_purge_failed',
    jsonb_build_object('error', sqlerrm));
  return jsonb_build_object('ok', false, 'error', sqlerrm);
end $$;

