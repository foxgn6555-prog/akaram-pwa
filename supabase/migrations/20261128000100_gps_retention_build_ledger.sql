-- ───────────────────────────────────────────────────────────────────────────────────────
-- ⑦ واجهة الإعدادات: نافذة الساعات + الحالة المحمية
-- ───────────────────────────────────────────────────────────────────────────────────────
create or replace function public.gps_history_purge_get() returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
declare
  v_cron boolean := false;
  s      public.gps_history_purge_settings;
  v_wait jsonb := '[]'::jsonb;
begin
  perform app.require_it();
  select * into s from public.gps_history_purge_settings where id = 1;

  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    execute $q$select exists (select 1 from cron.job where jobname = 'gps-history-purge-midnight' and active)$q$ into v_cron;
  end if;

  select coalesce(jsonb_agg(jsonb_build_object('day', x.day, 'rows', x.rows) order by x.day), '[]'::jsonb)
    into v_wait
    from (
      select app.map_baghdad_day(h.fix_time) as day, count(*) as rows
        from public.gps_device_position_history h
       where h.fix_time < now() - make_interval(hours => s.keep_hours)
       group by 1
    ) x
   where not app.gps_day_is_certified(x.day);

  return to_jsonb(s) - 'id' || jsonb_build_object(
    'scheduled', v_cron,
    'runs_at', '00:00 بغداد (21:00 UTC)',
    'build_runs_at', '23:30 بغداد (20:30 UTC)',
    'current_rows', (select count(*) from public.gps_device_position_history),
    'current_bytes', pg_total_relation_size('public.gps_device_position_history'::regclass),
    'last_freed_bytes', greatest(coalesce(s.last_bytes_before, 0) - coalesce(s.last_bytes_after, 0), 0),
    'waiting_days', v_wait,
    'waiting_rows', (select coalesce(sum((e ->> 'rows')::bigint), 0) from jsonb_array_elements(v_wait) e)
  );
end $$;

revoke all on function public.gps_history_purge_get() from public, anon;
grant execute on function public.gps_history_purge_get() to authenticated;

-- توقيع جديد (boolean, int) — يجب حذف القديم (boolean) وإلا نشأ overloadان
drop function if exists public.gps_history_purge_set(boolean);

create or replace function public.gps_history_purge_set(p_enabled boolean default null, p_keep_hours int default null)
returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare v_h int;
begin
  perform app.require_it();
  if p_keep_hours is not null and (p_keep_hours < 12 or p_keep_hours > 720) then
    raise exception 'RETENTION_INPUT_INVALID: keep_hours' using errcode = 'invalid_parameter_value';
  end if;

  update public.gps_history_purge_settings
     set enabled    = coalesce(p_enabled, enabled),
         keep_hours = coalesce(p_keep_hours, keep_hours),
         updated_by = auth.uid(),
         updated_at = now()
   where id = 1
  returning keep_hours into v_h;

  perform app.data_retention_log(null, 'gps_position_history', 'purge_settings_set',
    jsonb_build_object('enabled', p_enabled, 'keep_hours', v_h));
  return public.gps_history_purge_get();
end $$;

revoke all on function public.gps_history_purge_set(boolean, int) from public, anon;
grant execute on function public.gps_history_purge_set(boolean, int) to authenticated;

-- ───────────────────────────────────────────────────────────────────────────────────────
-- ⑧ المجدول: البناء 20:30 UTC ثم التفريغ 21:00 UTC — الترتيب هو الضمان
-- ───────────────────────────────────────────────────────────────────────────────────────
do $$ begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.unschedule(jobid) from cron.job
      where jobname in ('gps-visits-build-nightly', 'gps-history-purge-midnight');
    perform cron.schedule('gps-visits-build-nightly', '30 20 * * *', $job$ select app.gps_visits_build_scan(4) $job$);
    perform cron.schedule('gps-history-purge-midnight', '0 21 * * *', $job$ select app.gps_history_daily_purge() $job$);
  else
    raise notice 'pg_cron غير متاح — البناء والتفريغ الآليان يتطلبان تفعيله';
  end if;
end $$;

