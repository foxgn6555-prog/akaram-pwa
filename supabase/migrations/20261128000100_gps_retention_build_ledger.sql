-- ───────────────────────────────────────────────────────────────────────────────────────
-- ② معيار الشهادة — دالة واحدة تُستخدم في التفريغ والواجهة والاختبار
--    الشهادة صحيحة إذا: كل زون له صفّ built/empty، **و** أحدث نقطة في اليوم لم تتجاوز
--    points_at_build (أي أن البناء شمل كل ما وصل). أي نقطة متأخرة تُبطلها.
-- ───────────────────────────────────────────────────────────────────────────────────────
create or replace function app.gps_day_is_certified(p_day date) returns boolean
language plpgsql stable security definer set search_path = public, app as $$
declare
  v_zones   int;
  v_certs   int;
  v_newest  timestamptz;
  v_built_to timestamptz;
begin
  select count(*) into v_zones from public.map_zones;
  if coalesce(v_zones, 0) = 0 then return false; end if;

  select count(*) into v_certs from public.gps_visit_builds g
   where g.day = p_day and g.status in ('built', 'empty');
  if v_certs < v_zones then return false; end if;

  select max(h.fix_time) into v_newest
    from public.gps_device_position_history h
   where app.map_baghdad_day(h.fix_time) = p_day;

  if v_newest is null then return true; end if;  -- لا نقاط ⇒ كلها empty ⇒ الشهادة مكتملة

  -- أقل «أحدث نقطة مبنية» بين الزونات: إن لم تشمل كل الزونات أحدث نقطة فالشهادة ناقصة
  select min(coalesce(g.points_at_build, 'epoch'::timestamptz)) into v_built_to
    from public.gps_visit_builds g
   where g.day = p_day and g.status = 'built';

  return coalesce(v_built_to >= v_newest, false);
end $$;

comment on function app.gps_day_is_certified(date) is
  'هل بُني يوم بغدادي بالكامل؟ شرط إلزامي قبل حذف أي نقطة منه. ترفض الشهادة لو وصلت نقاط أحدث من البناء.';

revoke all on function app.gps_day_is_certified(date) from public, anon, authenticated;

-- غلاف عام للقراءة: تحتاجه الواجهة لتعرض «محمي / غير محمي» قبل أي حذف
create or replace function public.map_day_is_certified(p_day date) returns boolean
language plpgsql stable security definer set search_path = public, app as $$
begin
  if auth.uid() is null or not app.has_role(array['ops_room','ops_room_manager','it_admin','super_admin']) then
    raise exception 'MAP_FORBIDDEN' using errcode = 'insufficient_privilege';
  end if;
  return app.gps_day_is_certified(p_day);
end $$;

revoke all on function public.map_day_is_certified(date) from public, anon;
grant execute on function public.map_day_is_certified(date) to authenticated;

-- ───────────────────────────────────────────────────────────────────────────────────────
-- ③ الغلاف اليدوي: بناء يوم بغدادي + تسجيل الشهادة
--    · النافذة تُحسب بـapp.map_day_bounds لا بـ'T00:00:00Z' (المصدر الأصلي لخلل الـUTC)
--    · يوم جارٍ مرفوض: النافذة غير مغلقة، والشهادة عليه كذب
-- ───────────────────────────────────────────────────────────────────────────────────────
create or replace function public.map_visit_build_logged(
  p_zone    uuid,
  p_day     date,
  p_min_dwell_seconds integer default 60,
  p_max_gap_seconds   integer default 300
) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  b        record;
  r        record;
  v_t0     timestamptz := clock_timestamp();
  v_pts    bigint;
  v_newest timestamptz;
  v_ms     int;
begin
  perform public.map_require_editor();
  if p_day is null then
    raise exception 'MAP_VISIT_DAY_REQUIRED' using errcode = 'invalid_parameter_value';
  end if;
  if p_day >= app.map_baghdad_day(now()) then
    raise exception 'MAP_VISIT_DAY_NOT_CLOSED: يوم % لم ينتهِ بعد — لا شهادة على يوم جارٍ', p_day
      using errcode = 'invalid_parameter_value';
  end if;

  select * into b from app.map_day_bounds(p_day);

  select count(*), max(h.fix_time) into v_pts, v_newest
    from public.gps_device_position_history h
    join public.gps_vehicle_bindings vb on vb.device_id = h.device_id
   where h.fix_time >= b.day_start and h.fix_time < b.day_end;

  -- لا نقاط ⇒ 'empty' صريح (لا شيء يُحذف، والشهادة مكتملة بلا مخاطرة)
  if coalesce(v_pts, 0) = 0 then
    insert into public.gps_visit_builds
      (zone_id, day, status, trigger_kind, visits_created, visits_merged, places_scanned, skipped_visits,
       points_in_day, points_at_build, started_at, finished_at, duration_ms, actor_id, actor_name)
    values
      (p_zone, p_day, 'empty', 'manual', 0, 0, 0, 0, 0, null, v_t0, clock_timestamp(), 0,
       auth.uid(), case when auth.uid() is null then null else app.user_display_name(auth.uid()) end)
    on conflict (zone_id, day) do update set
      status = 'empty', trigger_kind = 'manual', visits_created = 0, visits_merged = 0,
      places_scanned = 0, skipped_visits = 0, points_in_day = 0, points_at_build = null,
      started_at = excluded.started_at, finished_at = excluded.finished_at, duration_ms = 0,
      error = null, actor_id = excluded.actor_id, actor_name = excluded.actor_name;
    return jsonb_build_object('ok', true, 'day', p_day, 'status', 'empty', 'visits_created', 0, 'points', 0);
  end if;

  select * into r from app.map_build_visits(p_zone, b.day_start, b.day_end, null,
                                            p_min_dwell_seconds, p_max_gap_seconds, true);
  v_ms := (extract(epoch from clock_timestamp() - v_t0) * 1000)::int;

  insert into public.gps_visit_builds
    (zone_id, day, status, trigger_kind, visits_created, visits_merged, places_scanned, skipped_visits,
     points_in_day, points_at_build, started_at, finished_at, duration_ms, actor_id, actor_name)
  values
    (p_zone, p_day, 'built', 'manual', r.visits_created, r.visits_merged, r.places_scanned, r.skipped_visits,
     v_pts, v_newest, v_t0, clock_timestamp(), v_ms,
     auth.uid(), case when auth.uid() is null then null else app.user_display_name(auth.uid()) end)
  on conflict (zone_id, day) do update set
    status = 'built', trigger_kind = 'manual',
    visits_created = excluded.visits_created, visits_merged = excluded.visits_merged,
    places_scanned = excluded.places_scanned, skipped_visits = excluded.skipped_visits,
    points_in_day = excluded.points_in_day, points_at_build = excluded.points_at_build,
    started_at = excluded.started_at, finished_at = excluded.finished_at,
    duration_ms = excluded.duration_ms, error = null,
    actor_id = excluded.actor_id, actor_name = excluded.actor_name;

  perform app.data_retention_log(null, 'map_visits', 'visit_build_manual',
    jsonb_build_object('zone', p_zone, 'day', p_day, 'created', r.visits_created,
                       'points', v_pts, 'duration_ms', v_ms));

  return jsonb_build_object('ok', true, 'day', p_day, 'status', 'built',
    'visits_created', r.visits_created, 'visits_merged', r.visits_merged,
    'places_scanned', r.places_scanned, 'skipped_visits', r.skipped_visits,
    'points', v_pts, 'duration_ms', v_ms);
end $$;

comment on function public.map_visit_build_logged(uuid, date, integer, integer) is
  'بناء زيارات يوم بغدادي واحد لزون واحد + تسجيل الشهادة. البديل المسجَّل لـmap_build_visits.';

revoke all on function public.map_visit_build_logged(uuid, date, integer, integer) from public, anon;
grant execute on function public.map_visit_build_logged(uuid, date, integer, integer) to authenticated;

-- ───────────────────────────────────────────────────────────────────────────────────────
-- ④ الغلاف القديم يبقى للتوافق — لكن **بلا نافذة تتجاوز يوماً واحداً**
--    العيب: كان يقبل أي نافذة ويحذف (p_replace) أوسع مما يبني عند فشل منتصف الطريق،
--    أو أوسع من اليوم المطلوب في الشفتات.
-- ───────────────────────────────────────────────────────────────────────────────────────
create or replace function public.map_build_visits(
  p_zone uuid,
  p_from timestamptz,
  p_to timestamptz,
  p_vehicle uuid default null,
  p_min_dwell_seconds integer default 60,
  p_max_gap_seconds integer default 300,
  p_replace boolean default true
)
returns table (visits_created integer, visits_merged integer, places_scanned integer, skipped_visits integer)
language plpgsql security definer set search_path = public, app as $$
declare
  v_days int;
begin
  perform public.map_require_editor();
  v_days := (app.map_baghdad_day(p_to) - app.map_baghdad_day(p_from)) + 1;
  if v_days > 1 then
    raise exception 'MAP_VISIT_WINDOW_TOO_WIDE: النافذة تغطي % يوماً — استخدم map_visit_build_logged بيوم واحد لتُسجَّل الشهادة', v_days
      using errcode = 'invalid_parameter_value';
  end if;
  return query select * from app.map_build_visits(p_zone, p_from, p_to, p_vehicle,
                                                  p_min_dwell_seconds, p_max_gap_seconds, p_replace);
end $$;

comment on function public.map_build_visits(uuid, timestamptz, timestamptz, uuid, integer, integer, boolean) is
  'غلاف متوافق: يقبل يوماً بغدادياً واحداً فقط ولا يُسجّل شهادة. للبناء المسجَّل استخدم map_visit_build_logged.';

-- ───────────────────────────────────────────────────────────────────────────────────────
-- ⑤ البناء الآلي: كل زون × كل يوم في نطاق المراجعة
-- ───────────────────────────────────────────────────────────────────────────────────────
create or replace function app.gps_visits_build_scan(p_lookback_days int default 4)
returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  z        record;
  dd       date;
  b        record;
  r        record;
  v_t0     timestamptz;
  v_built  int := 0;
  v_empty  int := 0;
  v_failed int := 0;
  v_skip   int := 0;
  v_pts    bigint;
  v_newest timestamptz;
  v_last   date := app.map_baghdad_day(now()) - 1;
  v_first  date;
  v_ms     int;
begin
  v_first := v_last - greatest(1, least(coalesce(p_lookback_days, 4), 30)) + 1;

  for z in select id from public.map_zones order by sort_order loop
    for dd in select g::date from generate_series(v_first::timestamp, v_last::timestamp, interval '1 day') g loop

      -- شهادة سارية؟ (كل الزونات + لا نقاط متأخرة) ⇒ تجاوز
      if app.gps_day_is_certified(dd) then
        v_skip := v_skip + 1;
        continue;
      end if;

      select * into b from app.map_day_bounds(dd);
      select count(*), max(h.fix_time) into v_pts, v_newest
        from public.gps_device_position_history h
        join public.gps_vehicle_bindings vb on vb.device_id = h.device_id
       where h.fix_time >= b.day_start and h.fix_time < b.day_end;

      v_t0 := clock_timestamp();

      if coalesce(v_pts, 0) = 0 then
        insert into public.gps_visit_builds
          (zone_id, day, status, trigger_kind, visits_created, visits_merged, places_scanned, skipped_visits,
           points_in_day, points_at_build, started_at, finished_at, duration_ms, actor_name)
        values (z.id, dd, 'empty', 'nightly', 0, 0, 0, 0, 0, null, v_t0, clock_timestamp(), 0, 'البناء الليلي')
        on conflict (zone_id, day) do update set
          status = 'empty', trigger_kind = 'nightly', points_in_day = 0, points_at_build = null,
          started_at = excluded.started_at, finished_at = excluded.finished_at, duration_ms = 0, error = null;
        v_empty := v_empty + 1;
        continue;
      end if;

      begin
        select * into r from app.map_build_visits(z.id, b.day_start, b.day_end, null, 60, 300, true);
        v_ms := (extract(epoch from clock_timestamp() - v_t0) * 1000)::int;
        insert into public.gps_visit_builds
          (zone_id, day, status, trigger_kind, visits_created, visits_merged, places_scanned, skipped_visits,
           points_in_day, points_at_build, started_at, finished_at, duration_ms, actor_name)
        values (z.id, dd, 'built', 'nightly', r.visits_created, r.visits_merged, r.places_scanned,
                r.skipped_visits, v_pts, v_newest, v_t0, clock_timestamp(), v_ms, 'البناء الليلي')
        on conflict (zone_id, day) do update set
          status = 'built', trigger_kind = 'nightly',
          visits_created = excluded.visits_created, visits_merged = excluded.visits_merged,
          places_scanned = excluded.places_scanned, skipped_visits = excluded.skipped_visits,
          points_in_day = excluded.points_in_day, points_at_build = excluded.points_at_build,
          started_at = excluded.started_at, finished_at = excluded.finished_at,
          duration_ms = excluded.duration_ms, error = null;
        v_built := v_built + 1;
      exception when others then
        v_ms := (extract(epoch from clock_timestamp() - v_t0) * 1000)::int;
        insert into public.gps_visit_builds
          (zone_id, day, status, trigger_kind, points_in_day, points_at_build,
           started_at, finished_at, duration_ms, error, actor_name)
        values (z.id, dd, 'failed', 'nightly', v_pts, v_newest, v_t0, clock_timestamp(), v_ms,
                left(sqlerrm, 1000), 'البناء الليلي')
        on conflict (zone_id, day) do update set
          status = 'failed', trigger_kind = 'nightly', points_in_day = excluded.points_in_day,
          points_at_build = excluded.points_at_build, started_at = excluded.started_at,
          finished_at = excluded.finished_at, duration_ms = excluded.duration_ms, error = excluded.error;
        v_failed := v_failed + 1;
      end;
    end loop;
  end loop;

  perform app.data_retention_log(null, 'map_visits', 'visit_build_scan',
    jsonb_build_object('from', v_first, 'to', v_last, 'built', v_built, 'empty', v_empty,
                       'failed', v_failed, 'skipped', v_skip));

  -- فشل أي بناء يُبلَّغ فوراً — لا يجوز أن يُحذف اليوم بعده بصمت
  if v_failed > 0 then
    perform app.notify_by_role(array['it_admin', 'super_admin', 'ops_room_manager'],
      'تعذّر بناء الزيارات لـ' || v_failed || ' زون/يوم — التفريغ لن يمسّها',
      'البناء الليلي لم يكتمل. النقاط محفوظة، والتفريغ يتجاوز الأيام غير المبنية. راجع سجل البناء.',
      'error', '/ops-room/map-planning/visits');
  end if;

  return jsonb_build_object('ok', v_failed = 0, 'from', v_first, 'to', v_last,
    'built', v_built, 'empty', v_empty, 'failed', v_failed, 'skipped', v_skip);
end $$;

comment on function app.gps_visits_build_scan(int) is
  'البناء الآلي: كل زون × كل يوم في النطاق. يُعيد البناء عند ظهور نقاط متأخرة (الشهادة تُبطل).';

revoke all on function app.gps_visits_build_scan(int) from public, anon, authenticated;

-- واجهة العمليات/IT: تشغيل البناء المتأخر يدوياً بعد سحب تاريخ قديم من المزوّد
create or replace function public.gps_visits_build_run(p_lookback_days int default 4) returns jsonb
language plpgsql security definer set search_path = public, app as $$
