create policy "vehicles: إدارة IT" on public.vehicles
  for all to authenticated
  using      (app.has_role(array['it_admin', 'super_admin']))
  with check (app.has_role(array['it_admin', 'super_admin']));

create policy "positions: قراءة IT" on public.vehicle_positions
  for select to authenticated
  using (app.has_role(array['it_admin', 'super_admin']));

create policy "events: قراءة IT" on public.gps_events
  for select to authenticated
  using (app.has_role(array['it_admin', 'super_admin']));

create index idx_positions_vehicle_time on public.vehicle_positions (vehicle_id, fix_time desc);
create index idx_events_vehicle_time    on public.gps_events (vehicle_id, occurred_at desc);
create index idx_vehicles_provider      on public.vehicles (gps_provider_id);

-- ── سجل التكاملات + إعدادات النظام ──
create table public.integration_logs (
  id           bigint generated by default as identity primary key,
  provider     text not null,                        -- biometric / gps:{name}
  direction    text not null check (direction in ('inbound', 'outbound')),
  endpoint     text,
  status       text not null default 'success'
               check (status in ('success', 'error', 'rejected')),
  payload      jsonb not null default '{}',
  error_note   text,
  created_at   timestamptz not null default now()
);

create table public.system_settings (
  key        text primary key,
  value      jsonb not null default '{}',
  updated_by uuid references auth.users (id) on delete set null,
  updated_at timestamptz not null default now()
);

alter table public.integration_logs enable row level security;
alter table public.system_settings  enable row level security;

create policy "ilogs: قراءة IT" on public.integration_logs
  for select to authenticated
  using (app.has_role(array['it_admin', 'super_admin']));

create policy "settings: قراءة للمصادقين" on public.system_settings
  for select to authenticated using (true);

create policy "settings: إدارة IT" on public.system_settings
  for all to authenticated
  using      (app.has_role(array['it_admin', 'super_admin']))
  with check (app.has_role(array['it_admin', 'super_admin']));

create index idx_ilogs_provider_time on public.integration_logs (provider, created_at desc);

-- ── حالة الجهاز عبر دالة آمنة (يستدعيها المستقبل بدون مصادقة) ──
create or replace function app.biometric_touch(p_sn text)
returns void
language sql
security definer
set search_path = public
as $$
  update public.biometric_devices
  set last_seen_at = now()
  where serial_number = p_sn and is_active;
$$;

revoke all on function app.biometric_touch(text) from public, anon, authenticated;

create trigger trg_vehicles_updated_at
  before update on public.vehicles for each row execute function app.set_updated_at();

do $$ begin
  execute format('create trigger trg_audit_biometric_devices after insert or update or delete on public.biometric_devices
                  for each row execute function app.audit_trigger();');
end $$;
