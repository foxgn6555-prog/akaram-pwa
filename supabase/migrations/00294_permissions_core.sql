revoke all on function app.perm_audit(uuid, uuid, text, jsonb) from public, anon, authenticated;

create or replace function app.perm_require_manager(p_target uuid) returns void
language plpgsql stable security definer set search_path = public, app as $$
begin
  perform app.require_it();
  if p_target is not null and p_target = auth.uid() then raise exception 'PERMISSION_SELF_EDIT'; end if;
  if p_target is not null and not exists (select 1 from auth.users where id = p_target) then raise exception 'IT_USER_NOT_FOUND'; end if;
  if p_target is not null and exists (select 1 from public.user_roles where user_id = p_target and role = 'super_admin')
     and not app.has_role(array['super_admin']) then raise exception 'PERMISSION_TARGET_SUPER_ADMIN'; end if;
end$$;
revoke all on function app.perm_require_manager(uuid) from public, anon, authenticated;

/** إنشاء/تعديل قالب: {id?, name, description?, is_active?} */
create or replace function public.it_permission_template_save(p jsonb) returns uuid
language plpgsql security definer set search_path = public, app as $$
declare v_id uuid := nullif(p->>'id', '')::uuid; v_name text := trim(coalesce(p->>'name', ''));
begin
  perform app.perm_require_manager(null);
  if length(v_name) < 2 then raise exception 'PERMISSION_TEMPLATE_NAME_INVALID'; end if;
  if v_id is null then
    insert into public.permission_templates (name, description, is_active, created_by, updated_by)
    values (v_name, nullif(trim(coalesce(p->>'description', '')), ''), coalesce((p->>'is_active')::boolean, true), auth.uid(), auth.uid()) returning id into v_id;
    perform app.perm_audit(null, v_id, 'template_create', jsonb_build_object('name', v_name));
  else
    update public.permission_templates set name = v_name, description = nullif(trim(coalesce(p->>'description', '')), ''),
      is_active = coalesce((p->>'is_active')::boolean, is_active), updated_by = auth.uid(), updated_at = now() where id = v_id;
    if not found then raise exception 'PERMISSION_TEMPLATE_NOT_FOUND'; end if;
    perform app.perm_audit(null, v_id, 'template_update', p - 'id');
  end if;
  return v_id;
end$$;

/** استبدال قواعد قالب كاملة: [{unit_key, action, effect}] */
create or replace function public.it_permission_template_rules_set(p_template uuid, p_rules jsonb) returns integer
language plpgsql security definer set search_path = public, app as $$
declare n integer;
begin
  perform app.perm_require_manager(null);
  if not exists (select 1 from public.permission_templates where id = p_template) then raise exception 'PERMISSION_TEMPLATE_NOT_FOUND'; end if;
  if jsonb_typeof(coalesce(p_rules, '[]'::jsonb)) <> 'array' then raise exception 'PERMISSION_RULES_INVALID'; end if;
  if exists (select 1 from jsonb_array_elements(coalesce(p_rules, '[]'::jsonb)) r
             left join public.permission_units u on u.key = r->>'unit_key'
             where u.key is null or not ((r->>'action') = any(u.actions)) or (r->>'effect') not in ('allow','deny')) then
    raise exception 'PERMISSION_RULES_INVALID';
  end if;
  delete from public.permission_template_rules where template_id = p_template;
  insert into public.permission_template_rules (template_id, unit_key, action, effect)
  select p_template, r->>'unit_key', r->>'action', r->>'effect' from jsonb_array_elements(coalesce(p_rules, '[]'::jsonb)) r
  on conflict (template_id, unit_key, action) do update set effect = excluded.effect;
  get diagnostics n = row_count;
  update public.permission_templates set updated_by = auth.uid(), updated_at = now() where id = p_template;
  perform app.perm_audit(null, p_template, 'template_rules', jsonb_build_object('count', n));
  return n;
end$$;

create or replace function public.it_permission_template_delete(p_template uuid) returns void
language plpgsql security definer set search_path = public, app as $$
declare v_name text; n integer;
begin
  perform app.perm_require_manager(null);
  select name into v_name from public.permission_templates where id = p_template;
  if v_name is null then raise exception 'PERMISSION_TEMPLATE_NOT_FOUND'; end if;
  select count(*) into n from public.user_permission_template where template_id = p_template;
  if n > 0 then raise exception 'PERMISSION_TEMPLATE_IN_USE' using detail = n::text; end if;
  delete from public.permission_templates where id = p_template;
  perform app.perm_audit(null, p_template, 'template_delete', jsonb_build_object('name', v_name));
end$$;

/** إسناد قالب لشخص (null = إزالة) */
create or replace function public.it_user_permission_template_set(p_user uuid, p_template uuid) returns void
language plpgsql security definer set search_path = public, app as $$
begin
  perform app.perm_require_manager(p_user);
  if p_template is null then
    delete from public.user_permission_template where user_id = p_user;
    perform app.perm_audit(p_user, null, 'user_template_clear', '{}'::jsonb);
  else
    if not exists (select 1 from public.permission_templates where id = p_template and is_active) then raise exception 'PERMISSION_TEMPLATE_NOT_FOUND'; end if;
    insert into public.user_permission_template (user_id, template_id, assigned_by) values (p_user, p_template, auth.uid())
    on conflict (user_id) do update set template_id = excluded.template_id, assigned_by = auth.uid(), assigned_at = now();
    perform app.perm_audit(p_user, p_template, 'user_template_set', '{}'::jsonb);
  end if;
end$$;

/** استثناء فردي (p_effect null = إزالة الاستثناء) */
create or replace function public.it_user_permission_override_set(p_user uuid, p_unit text, p_action text, p_effect text, p_reason text default null) returns void
language plpgsql security definer set search_path = public, app as $$
declare u public.permission_units;
begin
  perform app.perm_require_manager(p_user);
  select * into u from public.permission_units where key = p_unit;
  if u.key is null or not (p_action = any(u.actions)) then raise exception 'PERMISSION_RULES_INVALID'; end if;
  if p_effect is null then
    delete from public.user_permission_overrides where user_id = p_user and unit_key = p_unit and action = p_action;
    perform app.perm_audit(p_user, null, 'override_clear', jsonb_build_object('unit', p_unit, 'action', p_action));
    return;
  end if;
  if p_effect not in ('allow', 'deny') then raise exception 'PERMISSION_RULES_INVALID'; end if;
  insert into public.user_permission_overrides (user_id, unit_key, action, effect, reason, created_by)
  values (p_user, p_unit, p_action, p_effect, nullif(trim(coalesce(p_reason, '')), ''), auth.uid())
  on conflict (user_id, unit_key, action) do update set effect = excluded.effect, reason = excluded.reason, created_by = auth.uid(), created_at = now();
  perform app.perm_audit(p_user, null, 'override_set', jsonb_build_object('unit', p_unit, 'action', p_action, 'effect', p_effect, 'reason', p_reason));
end$$;

/** معاينة «كما يراه»: الصلاحيات الفعلية + مصدر كل إجراء */
create or replace function public.it_user_permissions_effective(p_user uuid)
returns table(unit_key text, portal text, label text, parent_key text, sort integer, action text, allowed boolean, source text, reason text)
language plpgsql stable security definer set search_path = public, app as $$
declare r text; is_sa boolean;
begin
  perform app.require_it();
  if not exists (select 1 from auth.users where id = p_user) then raise exception 'IT_USER_NOT_FOUND'; end if;
  is_sa := exists (select 1 from public.user_roles where user_id = p_user and role = 'super_admin');
  return query
  select u.key, u.portal, u.label, u.parent_key, u.sort, a,
         app.can(p_user, u.key, a),
         case when is_sa then 'super_admin'
              when o.effect is not null then 'override'
              when tr.effect is not null then 'template'
              when exists (select 1 from public.user_roles ur join public.permission_portal_roles pr on pr.role = ur.role where ur.user_id = p_user and pr.portal = u.portal) then 'role'
              else 'none' end,
         o.reason
  from public.permission_units u
  cross join lateral unnest(u.actions) a
  left join public.user_permission_overrides o on o.user_id = p_user and o.unit_key = u.key and o.action = a
  left join public.user_permission_template ut on ut.user_id = p_user
  left join public.permission_templates t on t.id = ut.template_id and t.is_active
  left join public.permission_template_rules tr on tr.template_id = t.id and tr.unit_key = u.key and tr.action = a
  order by u.sort, array_position(array['view','create','edit','decide','execute','export','delete'], a);
end$$;

create or replace function public.it_permission_audit_list(p_user uuid default null, p_template uuid default null, p_limit integer default 100)
returns table(id bigint, actor_id uuid, actor_name text, target_user uuid, template_id uuid, kind text, detail jsonb, created_at timestamptz)
language plpgsql stable security definer set search_path = public, app as $$
begin
  perform app.require_it();
  return query select a.id, a.actor_id, app.user_display_name(a.actor_id), a.target_user, a.template_id, a.kind, a.detail, a.created_at
  from public.permission_audit a
  where (p_user is null or a.target_user = p_user) and (p_template is null or a.template_id = p_template)
  order by a.created_at desc limit greatest(1, least(coalesce(p_limit, 100), 500));
end$$;

