create or replace function public.can_i(p_unit text, p_action text default 'view') returns boolean
language sql stable security definer set search_path = public, app as $$ select app.can(auth.uid(), p_unit, p_action) $$;
revoke all on function public.can_i(text, text) from public, anon;
grant execute on function public.can_i(text, text) to authenticated;

/** الصلاحيات الفعلية لمستخدم: {unit_key: [actions...]} — المسموح فقط */
create or replace function app.effective_permissions(p_user uuid) returns jsonb
language sql stable security definer set search_path = public, app as $$
  select coalesce(jsonb_object_agg(k, acts order by k), '{}'::jsonb) from (
    select u.key k, jsonb_agg(a order by array_position(array['view','create','edit','decide','execute','export','delete'], a)) acts
    from public.permission_units u cross join lateral unnest(u.actions) a
    where app.can(p_user, u.key, a)
    group by u.key
  ) s
$$;
revoke all on function app.effective_permissions(uuid) from public, anon, authenticated;

