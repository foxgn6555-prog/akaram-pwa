-- 00294 (00350 الجولة A) — نظام الصلاحيات الموحّد: وحدات × إجراءات، قوالب، استثناءات فردية، حسم واحد
--   الطبقات بترتيب الحسم (الأعلى يغلب):
--     ① super_admin: كل شيء دائماً (لا يُقيَّد)
--     ② استثناء فردي  user_permission_overrides (allow/deny لإجراء محدد في وحدة محددة)
--     ③ قالب الشخص   permission_templates + rules (قالب واحد لكل شخص؛ قواعده allow/deny)
--     ④ الدور الثابت: صاحب دور البوابة يملك كل إجراءات وحداتها (= السلوك قبل هذا الترحيل، فلا ينكسر أحد)
--     ⑤ غير ذلك: ممنوع
--   ثوابت: لا أحد يعدّل صلاحيات نفسه؛ «عرض» الرئيسية لكل بوابة لا يُحجب عن صاحب دورها؛ كل تغيير يُسجَّل في permission_audit.
--   الكتالوج (permission_units) مولَّد من src/config/permission-catalog.ts — اختبار عقد يضمن التطابق.
-- ═══════════════════════════════════════════════════════════════════════════════

create table if not exists public.permission_units (
  key        text primary key,
  portal     text not null,
  path       text not null,
  label      text not null,
  parent_key text,
  actions    text[] not null default '{view}',
  sort       integer not null default 0,
  check (actions <@ array['view','create','edit','decide','execute','export','delete']::text[] and 'view' = any(actions))
);
create index if not exists permission_units_portal_idx on public.permission_units (portal, sort);

create table if not exists public.permission_portal_roles (
  portal text primary key,
  role   text not null
);

create table if not exists public.permission_templates (
  id          uuid primary key default gen_random_uuid(),
  name        text not null unique check (length(trim(name)) between 2 and 80),
  description text check (description is null or length(description) <= 300),
  is_active   boolean not null default true,
  created_by  uuid references auth.users(id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_by  uuid references auth.users(id) on delete set null,
  updated_at  timestamptz not null default now()
);

create table if not exists public.permission_template_rules (
  template_id uuid not null references public.permission_templates(id) on delete cascade,
  unit_key    text not null references public.permission_units(key) on delete cascade,
  action      text not null check (action in ('view','create','edit','decide','execute','export','delete')),
  effect      text not null check (effect in ('allow','deny')),
  primary key (template_id, unit_key, action)
);
create index if not exists permission_template_rules_unit_idx on public.permission_template_rules (unit_key);

create table if not exists public.user_permission_template (
  user_id     uuid primary key references auth.users(id) on delete cascade,
  template_id uuid not null references public.permission_templates(id) on delete cascade,
  assigned_by uuid references auth.users(id) on delete set null,
  assigned_at timestamptz not null default now()
);
create index if not exists user_permission_template_tpl_idx on public.user_permission_template (template_id);

create table if not exists public.user_permission_overrides (
  user_id    uuid not null references auth.users(id) on delete cascade,
  unit_key   text not null references public.permission_units(key) on delete cascade,
  action     text not null check (action in ('view','create','edit','decide','execute','export','delete')),
  effect     text not null check (effect in ('allow','deny')),
  reason     text check (reason is null or length(reason) <= 300),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  primary key (user_id, unit_key, action)
);

create table if not exists public.permission_audit (
  id          bigint generated by default as identity primary key,
  actor_id    uuid references auth.users(id) on delete set null,
  target_user uuid references auth.users(id) on delete set null,
  template_id uuid,
  kind        text not null,
  detail      jsonb not null default '{}',
  created_at  timestamptz not null default now()
);
create index if not exists permission_audit_target_idx on public.permission_audit (target_user, created_at desc);
create index if not exists permission_audit_tpl_idx on public.permission_audit (template_id, created_at desc);

alter table public.permission_units enable row level security;
alter table public.permission_portal_roles enable row level security;
alter table public.permission_templates enable row level security;
alter table public.permission_template_rules enable row level security;
alter table public.user_permission_template enable row level security;
alter table public.user_permission_overrides enable row level security;
alter table public.permission_audit enable row level security;
