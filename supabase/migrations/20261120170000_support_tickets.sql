-- 20261120170000_support_tickets.sql — وحدة الدعم الفني (الجولة ٥)
--
-- المتطلب ⑤: وحدة دعم فني في كل البوابات — رقم تواصل + نموذج طلب (نص + صورة) يصل إلى بوابة IT.
--
-- لماذا جدول جديد بدل it_tickets القائم؟
--   it_tickets.created_by يشير إلى employees(id) لا auth.users، فمن لا سجل موظف له (كثير من
--   حسابات التشغيل) لا يستطيع إنشاء تذكرة. الجدول القديم فارغ (0 صف) ويبقى كما هو.
--
-- ما تفعله الترحيلة:
--   ① جدول public.support_tickets + ترقيم متسلسل + قيود صريحة.
--   ② حاوية تخزين خاصة support-attachments (صور فقط، 10MB) مع سياسات: المالك يرفع في مجلده،
--      والملاك + تقنية المعلومات يقرأون.
--   ③ دوال: support_ticket_create (أي مستخدم مصادق) · support_tickets_list · support_ticket_decide
--      (IT فقط) · support_contact (رقم الدعم وساعات العمل).
--   ④ إشعار فوري لمسؤولي تقنية المعلومات عند كل تذكرة جديدة (app.hr_notify القائم).
--
-- التراجع: drop الجدول والدوال الأربع وحاوية التخزين.

-- ⓪ فحص مسبق
do $pre$
begin
  if to_regprocedure('app.hr_notify(uuid,text,text,text,text,text)') is null then
    raise exception 'SUPPORT_PRECHECK: app.hr_notify غير موجودة';
  end if;
  if to_regprocedure('app.require_it_admin(text)') is null then
    raise exception 'SUPPORT_PRECHECK: نفّذ 20261120120000 أولاً';
  end if;
end $pre$;

-- ① الجدول
create table if not exists public.support_tickets (
  id               uuid primary key default gen_random_uuid(),
  ticket_number    bigint generated by default as identity unique,
  created_by       uuid not null references auth.users (id) on delete cascade,
  requester_name   text,
  contact_phone    text,
  source_portal    text,
  category         text not null default 'other' check (category in ('hardware', 'software', 'network', 'account', 'other')),
  priority         text not null default 'medium' check (priority in ('low', 'medium', 'high', 'critical')),
  status           text not null default 'open' check (status in ('open', 'in_progress', 'resolved', 'closed')),
  title            text not null check (char_length(title) between 3 and 150),
  description      text not null check (char_length(description) between 3 and 4000),
  attachment_paths text[] not null default '{}',
  admin_note       text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  resolved_at      timestamptz
);

comment on table public.support_tickets is
  'تذاكر الدعم الفني من كل البوابات إلى بوابة تقنية المعلومات. القراءة والكتابة عبر دوال محروسة فقط.';

alter table public.support_tickets enable row level security;
revoke all on table public.support_tickets from anon, authenticated;

create index if not exists idx_support_tickets_status on public.support_tickets (status, created_at desc);
create index if not exists idx_support_tickets_creator on public.support_tickets (created_by, created_at desc);

-- ② حاوية الصور
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('support-attachments', 'support-attachments', false, 10485760, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;

drop policy if exists "support-attachments: رفع إلى مجلدي" on storage.objects;
create policy "support-attachments: رفع إلى مجلدي" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'support-attachments' and split_part(name, '/', 1) = auth.uid()::text);

drop policy if exists "support-attachments: قراءة المالك وتقنية المعلومات" on storage.objects;
create policy "support-attachments: قراءة المالك وتقنية المعلومات" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'support-attachments'
    and (
      split_part(name, '/', 1) = auth.uid()::text
      or exists (select 1 from public.user_roles ur where ur.user_id = auth.uid() and ur.role = 'it_admin')
    )
  );

-- ③ الدوال

-- إنشاء تذكرة (أي مستخدم مصادق — من أي بوابة)
create or replace function public.support_ticket_create(
  p_title        text,
  p_description  text,
  p_category     text default 'other',
  p_priority     text default 'medium',
  p_source_portal text default null,
  p_contact_phone text default null,
  p_attachments  text[] default '{}'
) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  v_me uuid := auth.uid();
  v_id uuid;
  v_number bigint;
  v_path text;
  v_admin uuid;
begin
  if v_me is null then
    raise exception 'PERMISSION_DENIED' using detail = 'لا جلسة';
  end if;
  if char_length(btrim(coalesce(p_title, ''))) < 3 or char_length(btrim(coalesce(p_title, ''))) > 150 then
    raise exception 'INVALID_INPUT' using detail = 'العنوان بين 3 و150 حرفاً';
  end if;
  if char_length(btrim(coalesce(p_description, ''))) < 3 or char_length(btrim(coalesce(p_description, ''))) > 4000 then
    raise exception 'INVALID_INPUT' using detail = 'الوصف بين 3 و4000 حرف';
  end if;
  if coalesce(p_category, 'other') not in ('hardware', 'software', 'network', 'account', 'other') then
    raise exception 'INVALID_INPUT' using detail = 'تصنيف غير معروف';
  end if;
  if coalesce(p_priority, 'medium') not in ('low', 'medium', 'high', 'critical') then
    raise exception 'INVALID_INPUT' using detail = 'أولوية غير معروفة';
  end if;
  if coalesce(array_length(p_attachments, 1), 0) > 3 then
    raise exception 'INVALID_INPUT' using detail = 'ثلاث صور كحد أقصى';
  end if;
  -- كل مرفق يجب أن يكون في مجلد صاحبه (يمنع إرفاق ملفات غيره)
  if p_attachments is not null then
    foreach v_path in array p_attachments loop
      if split_part(v_path, '/', 1) <> v_me::text then
        raise exception 'INVALID_INPUT' using detail = 'مرفق لا يخص المستخدم';
      end if;
    end loop;
  end if;
  if p_contact_phone is not null and char_length(p_contact_phone) > 30 then
    raise exception 'INVALID_INPUT' using detail = 'رقم التواصل طويل';
  end if;

  insert into public.support_tickets
    (created_by, requester_name, contact_phone, source_portal, category, priority, title, description, attachment_paths)
  values
    (v_me, app.user_display_name(v_me), nullif(btrim(coalesce(p_contact_phone, '')), ''),
     nullif(btrim(coalesce(p_source_portal, '')), ''), coalesce(p_category, 'other'),
     coalesce(p_priority, 'medium'), btrim(p_title), btrim(p_description),
     coalesce(p_attachments, '{}'))
  returning id, ticket_number into v_id, v_number;

  -- إشعار كل مسؤولي تقنية المعلومات
  for v_admin in select ur.user_id from public.user_roles ur where ur.role = 'it_admin' loop
    perform app.hr_notify(v_admin, 'تذكرة دعم فني جديدة',
      '#' || v_number || ' · ' || btrim(p_title) || ' — ' || coalesce(app.user_display_name(v_me), '—'),
      '/it/login-support', 'support_ticket:' || v_id::text, 'info');
  end loop;

  perform app.security_event('policy_changed', 'info', v_me, null, null, null, null, null,
                             jsonb_build_object('action', 'support_ticket', 'ticket', v_number));

  return jsonb_build_object('id', v_id, 'ticket_number', v_number);
end $$;
revoke all on function public.support_ticket_create(text, text, text, text, text, text, text[]) from public, anon;
grant execute on function public.support_ticket_create(text, text, text, text, text, text, text[]) to authenticated;

-- قائمة التذاكر (تقنية المعلومات)
create or replace function public.support_tickets_list(p_status text default null)
returns table (
  id               uuid,
  ticket_number    bigint,
  created_by       uuid,
  requester_name   text,
  contact_phone    text,
  source_portal    text,
  category         text,
  priority         text,
  status           text,
  title            text,
  description      text,
  attachment_paths text[],
  admin_note       text,
  created_at       timestamptz,
  resolved_at      timestamptz
)
language plpgsql stable security definer set search_path = public, app as $$
begin
  perform app.require_it_admin('view');
  return query
    select t.id, t.ticket_number, t.created_by, t.requester_name, t.contact_phone, t.source_portal,
           t.category, t.priority, t.status, t.title, t.description, t.attachment_paths,
           t.admin_note, t.created_at, t.resolved_at
    from public.support_tickets t
    where p_status is null or t.status = p_status
    order by (case t.status when 'open' then 0 when 'in_progress' then 1 when 'resolved' then 2 else 3 end),
             t.created_at desc
    limit 300;
end $$;
revoke all on function public.support_tickets_list(text) from public, anon;
grant execute on function public.support_tickets_list(text) to authenticated;

-- تغيير حالة/ملاحظة (تقنية المعلومات)
create or replace function public.support_ticket_decide(p_id uuid, p_status text, p_note text default null)
returns void
language plpgsql security definer set search_path = public, app as $$
declare v_row public.support_tickets;
begin
  perform app.require_it_admin('edit');
  if p_status not in ('open', 'in_progress', 'resolved', 'closed') then
    raise exception 'INVALID_INPUT' using detail = 'حالة غير معروفة';
  end if;
  if p_note is not null and char_length(p_note) > 2000 then
    raise exception 'INVALID_INPUT' using detail = 'الملاحظة أطول من 2000 حرف';
  end if;
  select * into v_row from public.support_tickets where id = p_id for update;
  if v_row.id is null then
    raise exception 'TICKET_NOT_FOUND' using detail = p_id::text;
  end if;

  update public.support_tickets
     set status = p_status,
         admin_note = coalesce(nullif(btrim(coalesce(p_note, '')), ''), admin_note),
         resolved_at = case when p_status in ('resolved', 'closed') then coalesce(resolved_at, now()) else null end,
         updated_at = now()
   where id = p_id;

  perform app.hr_notify(v_row.created_by, 'تحديث على تذكرة الدعم #' || v_row.ticket_number,
    case p_status when 'in_progress' then 'جاري العمل عليها' when 'resolved' then 'تم الحل'
                  when 'closed' then 'أُغلقت' else 'أُعيد فتحها' end,
    '/employee', 'support_ticket_upd:' || p_id::text || ':' || p_status, 'info');
end $$;
revoke all on function public.support_ticket_decide(uuid, text, text) from public, anon;
grant execute on function public.support_ticket_decide(uuid, text, text) to authenticated;

-- رقم الدعم وساعات العمل (لكل البوابات)
create or replace function public.support_contact()
returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
declare v record;
begin
  if auth.uid() is null then
    raise exception 'PERMISSION_DENIED' using detail = 'لا جلسة';
  end if;
  select support_phone, business_hours, is_online into v from public.login_support_settings limit 1;
  return jsonb_build_object(
    'phone', coalesce(v.support_phone, null),
    'hours', coalesce(v.business_hours, null),
    'online', coalesce(v.is_online, false)
  );
end $$;
revoke all on function public.support_contact() from public, anon;
grant execute on function public.support_contact() to authenticated;

-- ⑤ فحص ذاتي
do $check$
begin
  if to_regclass('public.support_tickets') is null then
    raise exception 'SUPPORT_CHECK: الجدول لم يُنشأ';
  end if;
  if not exists (select 1 from storage.buckets where id = 'support-attachments') then
    raise exception 'SUPPORT_CHECK: حاوية المرفقات غير موجودة';
  end if;
  if (select count(*) from public.support_tickets) <> 0 then
    raise exception 'SUPPORT_CHECK: يجب أن تبدأ فارغة';
  end if;
end $check$;
