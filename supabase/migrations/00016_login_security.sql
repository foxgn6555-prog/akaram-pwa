--  · سجل محاولات الدخول + إقفال تلقائي (5 محاولات فاشلة → قفل 15 دقيقة)
--  · الدوال SECURITY DEFINER لأن الدخول يحدث قبل المصادقة (anon)
--  · الجدول بلا سياسات RLS → محصور تماماً بالدوال (لا قراءة مباشرة إطلاقاً)
-- طبقات الحماية الموازية (خارج هذه الـ migration):
--  · Rate limiting مدمج في Supabase Auth (لكل IP/بريد)
--  · CAPTCHA اختياري (انظر config.toml) · حارس المتصفح في الواجهة
