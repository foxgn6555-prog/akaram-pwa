-- فحص ذاتي: الدوال الأربع موجودة ومحمية (security definer + app.guard_duplicate) ومربوطة؛ وإلا تتوقف الترحيلة كلها
do $check$ declare r record; begin
  for r in select g.fn from unnest(array['disbursement_decide', 'disbursement_pay', 'disbursement_resubmit', 'finance_contractor_wages_close']) g(fn) loop
    if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                    where n.nspname = 'public' and p.proname = r.fn and p.prosecdef and p.prosrc like '%app.guard_duplicate(%') then
      raise exception 'M4_CHECK: الدالة % غير موجودة أو بلا حارس — نفّذ ترحيلات القاصة وطلبات الصرف وأجور المتعهدين أولاً', r.fn;
    end if;
    if not exists (select 1 from public.permission_write_bindings b where b.fn = r.fn) then
      raise exception 'M4_CHECK: لا ربط للدالة %', r.fn;
    end if;
  end loop;
end $check$;
