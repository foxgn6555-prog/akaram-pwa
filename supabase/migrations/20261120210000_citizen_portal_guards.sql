--
-- ما تكشفه هذه الترحيلة:
--   ① ثغرة استيلاء على الحساب في public.citizen_sign_in:
--      الصيغة القديمة كانت `insert … on conflict (phone) do update set token = gen_random_uuid()`،
--      أي أن أي شخص يعرف رقم هاتف مواطن يحصل على رمز جديد ويُبطل رمز صاحبه ⇒ يقرأ كل شكاواه
--      ومحادثاته ويتصرّف باسمه. لا OTP ولا تحقّق ملكية.
--   ② ثلاث دوال موظفين كانت ممنوحة لـ anon في القائمة البيضاء (00416):
--      citizen_complaints_report · citizen_complaint_set_status · citizen_complaint_add_note
--      محميّة داخلياً بـ app.has_role / app.citizen_is_staff، لكن كشفها لـ anon طبقة زائدة بلا داعٍ.
--   ③ خمس مساعدات في مخطط app ما زالت قابلة للتنفيذ بواسطة anon (وراثة الامتياز الافتراضي):
--      disbursement_json · disbursement_kind_label · activity_monthly_report ·
--      data_retention_catalog_disbursements · platform_reset_catalog_disbursements
--
-- ما تفعله:
--   ① جدول public.citizen_signin_attempts — عدّاد محاولات الدخول لكل رقم (لتقييد التخمين).
--   ② app.citizen_norm_name / app.citizen_name_matches — مطابقة اسم متسامحة (تطبيع عربي + احتواء الكلمات).
--   ③ إعادة كتابة public.citizen_sign_in:
--        · رقم جديد ⇒ إنشاء حساب وإرجاع رمزه (كما اليوم، returning=false).
--        · رقم قائم **بلا تدوير للرمز**: يُشترط تطابق الاسم، ويُعاد الرمز نفسه (returning=true)
--          — فلا يُبطل جهاز المواطن ولا ينتقل حسابه لمن يعرف الرقم فقط.
--        · الاسم غير المطابق ⇒ تسجيل المحاولة وإرجاع {error:'CITIZEN_IDENTITY_MISMATCH', attempts_left}
--          **بلا استثناء**: استثناء PostgreSQL يُلغي كل ما كُتب في نفس المعاملة، فتضيع المحاولة
--          ويصبح تقييد التخمين مستحيلاً. العقد الجديد: الدالة تُرجع كائن خطأ، والـSDK يحوّله إلى استثناء.
--        · خمس محاولات فاشلة في ساعة ⇒ {error:'CITIZEN_SIGNIN_LOCKED'}.
--   ④ سحب EXECUTE عن الدوال الثلاث من anon (تبقى لـ authenticated كما هي).
--   ⑤ سحب EXECUTE عن المساعدات الخمس من anon/public + منع وراثة الامتياز الافتراضي في مخطط app.
--
-- ما لا تغيّره: لا تعديل في بنية الشكاوى ولا في المحادثة ولا في سياسات التخزين،
-- ولا في الرموز القائمة (لا تُبطَل ولا تُدوَّر)، ولا في أي دالة أخرى.
--
-- التراجع: إعادة نص citizen_sign_in من 00168، ثم drop الجدول والدالتين، ثم
--          grant execute … to anon للدوال الثلاث والمساعدات الخمس.

-- ⓪ فحص مسبق
do $pre$
begin
  if to_regprocedure('public.citizen_sign_in(text,text)') is null then
    raise exception 'CITIZEN_GUARDS_PRECHECK: citizen_sign_in غير موجودة — نفّذ 00168 أولاً';
  end if;
  if to_regclass('public.citizen_accounts') is null then
    raise exception 'CITIZEN_GUARDS_PRECHECK: citizen_accounts غير موجود';
  end if;
  if to_regprocedure('app.citizen_norm_phone(text)') is null then
    raise exception 'CITIZEN_GUARDS_PRECHECK: app.citizen_norm_phone غير موجودة';
  end if;
  if pg_get_functiondef('public.citizen_sign_in(text,text)'::regprocedure) like '%token = gen_random_uuid()%'
     and to_regclass('public.citizen_signin_attempts') is null then
    raise notice 'CITIZEN_GUARDS: الصيغة القديمة (تدوير الرمز) مرصودة — سيُعاد التعريف';
  end if;
end $pre$;

-- ① عدّاد محاولات الدخول
create table if not exists public.citizen_signin_attempts (
  id      bigint generated by default as identity primary key,
  phone   text not null,
  outcome text not null check (outcome in ('created', 'returning', 'mismatch', 'locked')),
  at      timestamptz not null default now()
);
comment on table public.citizen_signin_attempts is
  'عدّاد محاولات دخول المواطن لكل رقم — لتقييد تخمين الاسم (5 محاولات فاشلة/ساعة). لا وصول مباشر من أي دور.';
alter table public.citizen_signin_attempts enable row level security;
revoke all on table public.citizen_signin_attempts from anon, authenticated;
create index if not exists idx_citizen_signin_attempts on public.citizen_signin_attempts (phone, at desc);

-- ② تطبيع الاسم ومطابقته (داخليتان — لا تنفيذ لأي دور)
create or replace function app.citizen_norm_name(p text) returns text[]
language sql immutable as $$
  select coalesce(array_agg(w order by ord), '{}'::text[])
  from unnest(regexp_split_to_array(
         regexp_replace(
           translate(lower(btrim(coalesce(p, ''))), 'أإآىة', 'ااايه'),
           '\s+', ' ', 'g'), ' ')) with ordinality as t(w, ord)
  where w <> ''
$$;
revoke all on function app.citizen_norm_name(text) from public, anon, authenticated;

/** مطابقة متسامحة: كل كلمات الاسم المخزَّن موجودة في الاسم المُدخل (الترتيب لا يهم).
 *  اسم مخزَّن من كلمة واحدة ⇒ يلزم تطابق تام بكلمة واحدة. */
create or replace function app.citizen_name_matches(p_stored text, p_input text) returns boolean
language plpgsql immutable as $$
declare s text[] := app.citizen_norm_name(p_stored); i text[] := app.citizen_norm_name(p_input);
begin
  if coalesce(array_length(s, 1), 0) = 0 or coalesce(array_length(i, 1), 0) = 0 then return false; end if;
  if array_length(s, 1) = 1 then
    return array_length(i, 1) = 1 and s[1] = i[1];
  end if;
  return i @> s;
end $$;
revoke all on function app.citizen_name_matches(text, text) from public, anon, authenticated;

-- ③ بوابة الدخول: بلا تدوير للرمز + مطابقة الاسم + تقييد المحاولات
create or replace function public.citizen_sign_in(p_name text, p_phone text) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  v_name text := btrim(regexp_replace(coalesce(p_name, ''), '\s+', ' ', 'g'));
  v_phone text;
  a public.citizen_accounts;
  v_denials int;
begin
  if length(v_name) < 3 or length(v_name) > 80 then raise exception 'CITIZEN_NAME_INVALID'; end if;
  v_phone := app.citizen_norm_phone(p_phone);

  -- تقييد التخمين: خمس محاولات فاشلة في الساعة الأخيرة
  select count(*) into v_denials
    from public.citizen_signin_attempts t
   where t.phone = v_phone and t.outcome = 'mismatch' and t.at > now() - interval '1 hour';
  if v_denials >= 5 then
    return jsonb_build_object('error', 'CITIZEN_SIGNIN_LOCKED',
                              'message', 'محاولات كثيرة على هذا الرقم — أعد المحاولة بعد ساعة');
  end if;

  select * into a from public.citizen_accounts where phone = v_phone;

  -- حساب جديد: الرمز يُنشأ مرة واحدة ويُسلَّم لصاحبه
  if a.id is null then
    insert into public.citizen_accounts (full_name, phone) values (v_name, v_phone) returning * into a;
    insert into public.citizen_signin_attempts (phone, outcome) values (v_phone, 'created');
    return jsonb_build_object('token', a.token, 'full_name', a.full_name, 'phone', a.phone, 'returning', false);
  end if;

  -- حساب قائم: لا تدوير للرمز — يلزم أن يطابق الاسم صاحب الرقم
  if not app.citizen_name_matches(a.full_name, v_name) then
    insert into public.citizen_signin_attempts (phone, outcome) values (v_phone, 'mismatch');
    delete from public.citizen_signin_attempts t
     where t.phone = v_phone and t.at < now() - interval '7 days';
    return jsonb_build_object('error', 'CITIZEN_IDENTITY_MISMATCH',
                              'message', 'الاسم لا يطابق صاحب هذا الرقم',
                              'attempts_left', greatest(0, 4 - v_denials));
  end if;

  update public.citizen_accounts set last_seen_at = now() where id = a.id;
  insert into public.citizen_signin_attempts (phone, outcome) values (v_phone, 'returning');
  return jsonb_build_object('token', a.token, 'full_name', a.full_name, 'phone', a.phone, 'returning', true);
end $$;
revoke all on function public.citizen_sign_in(text, text) from public;
grant execute on function public.citizen_sign_in(text, text) to anon, authenticated;

