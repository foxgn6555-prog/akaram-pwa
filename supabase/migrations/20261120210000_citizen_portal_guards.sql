do $check$
declare v_def text; v_n int;
begin
  -- منطق المطابقة
  if not app.citizen_name_matches('علي حسين', 'علي حسين كاظم') then
    raise exception 'CITIZEN_GUARDS_CHECK: الاسم الثلاثي يجب أن يطابق المخزَّن الثنائي';
  end if;
  if not app.citizen_name_matches('علي حسين', ' علي   حسين ') then
    raise exception 'CITIZEN_GUARDS_CHECK: تطبيع المسافات معطّل';
  end if;
  if app.citizen_name_matches('علي حسين', 'حسين محمد') then
    raise exception 'CITIZEN_GUARDS_CHECK: مطابقة مفرطة — اسم مختلف مرّ';
  end if;
  if app.citizen_name_matches('علي', 'علي حسين') then
    raise exception 'CITIZEN_GUARDS_CHECK: اسم مفرد مخزَّن يجب أن يلزم التطابق التام';
  end if;

  -- الدالة الجديدة بلا تدوير للرمز
  v_def := pg_get_functiondef('public.citizen_sign_in(text,text)'::regprocedure);
  if position('gen_random_uuid' in v_def) > 0 then
    raise exception 'CITIZEN_GUARDS_CHECK: ما زال تدوير الرمز في بوابة الدخول';
  end if;
  if position('CITIZEN_IDENTITY_MISMATCH' in v_def) = 0 then
    raise exception 'CITIZEN_GUARDS_CHECK: حارس مطابقة الاسم غير مطبَّق';
  end if;

  -- الأذونات
  if has_function_privilege('anon', 'public.citizen_complaints_report(date,date)', 'execute')
     or has_function_privilege('anon', 'public.citizen_complaint_set_status(uuid,text,text)', 'execute')
     or has_function_privilege('anon', 'public.citizen_complaint_add_note(uuid,text)', 'execute') then
    raise exception 'CITIZEN_GUARDS_CHECK: دوال الموظفين ما زالت مكشوفة للزائر';
  end if;
  if has_function_privilege('anon', 'app.disbursement_json(public.payroll_disbursements)', 'execute')
     or has_function_privilege('anon', 'app.activity_monthly_report()', 'execute') then
    raise exception 'CITIZEN_GUARDS_CHECK: مساعدات app ما زالت مكشوفة للزائر';
  end if;
  if not has_function_privilege('anon', 'app.citizen_token_valid(text)', 'execute') then
    raise exception 'CITIZEN_GUARDS_CHECK: citizen_token_valid يجب أن يبقى للزائر (سياسة التخزين)';
  end if;
  if not has_function_privilege('anon', 'public.citizen_sign_in(text,text)', 'execute')
     or not has_function_privilege('anon', 'public.citizen_my_complaints(uuid)', 'execute') then
    raise exception 'CITIZEN_GUARDS_CHECK: سُحبت بوابة المواطن بالخطأ';
  end if;
  if has_table_privilege('anon', 'public.citizen_signin_attempts', 'select')
     or has_table_privilege('authenticated', 'public.citizen_signin_attempts', 'select') then
    raise exception 'CITIZEN_GUARDS_CHECK: جدول المحاولات مكشوف';
  end if;
  select count(*) into v_n
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname like 'citizen\_%' and has_function_privilege('anon', p.oid, 'execute');
  if v_n <> 10 then
    raise exception 'CITIZEN_GUARDS_CHECK: عدد دوال الزائر يجب أن يكون 10، جاء %', v_n;
  end if;
end $check$;
