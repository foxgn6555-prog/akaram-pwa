-- 20261120120000 — أساس الجلسات والأحداث الأمنية (الجولة ١ من خطة الصلاحيات والأمان)
--
-- ما تفعله هذه الترحيلة (بنية فقط — لا واجهة، لا تغيير سلوك):
--   ① جدول سياسة الجلسات لكل حساب: account_session_policy
--      (max_sessions 1..10 · enforce · note · updated_by). السياسات **معطّلة افتراضياً**
--      (لا صف = جهاز واحد لكن enforce=false) ⇒ لا يمنع أي دخول اليوم.
--   ② جدول سجل الأحداث الأمنية: security_events
--      (دخول · فشل · تعارض أجهزة · تجاوز حد · إنهاء جلسة · تغيير سياسة)
--      مع IP وUser-Agent وsession_id وبصمة الجهاز المشفّرة، وأعمدة country/city
--      جاهزة للجولة ٤ (تُترك فارغة الآن — لا ندّعي معرفة الموقع).
--   ③ دوال داخلية: app.session_policy_for · app.session_active_count · app.security_event
--      وحاوية واحدة قابلة للاستدعاء من خدمة الحافة: public.security_event_record
--      (service_role فقط) — لتسجيل محاولات الدخول من staff-login.
--   ④ دوال قراءة/كتابة لبوابة تقنية المعلومات (بلا واجهة بعد):
--      session_policy_get · session_policy_set · session_policy_list · security_events_list
--      الحراسة الخادمية الآن بدور it_admin صراحةً (سابقة attendance_manual_activate)،
--      وتُستبدل بوحدة صلاحيات it.security.sessions في الجولة ٣ حين تُبنى الشاشة.
--
-- ما لا تغيّره: لا جدول قائم، لا عمود قائم، لا دالة قائمة، لا صلاحية قائمة، ولا صف بيانات.
-- الجلسات تُقرأ من auth.sessions (GoTrue) — لا سجل جلسات موازٍ (مصدر حقيقة واحد).
-- التراجع: drop table public.security_events, public.account_session_policy; drop الدوال الست.

-- ⓪ فحص مسبق: كل ما نعتمد عليه موجود، وإلا تتوقف الترحيلة قبل أي تغيير
do $pre$
begin
  if to_regclass('auth.users') is null then
    raise exception 'SESSION_CORE_PRECHECK: auth.users غير موجود';
  end if;
  if to_regprocedure('app.has_role(text[])') is null then
    raise exception 'SESSION_CORE_PRECHECK: app.has_role غير موجودة';
  end if;
end $pre$;

-- ① سياسة الجلسات لكل حساب — «عدد المستخدمين المسموح» للمتطلب ⑥
create table if not exists public.account_session_policy (
  user_id      uuid primary key references auth.users (id) on delete cascade,
  max_sessions smallint not null default 1 check (max_sessions between 1 and 10),
  enforce      boolean  not null default false,
  note         text     check (note is null or char_length(note) <= 500),
  updated_by   uuid     references auth.users (id) on delete set null,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

comment on table public.account_session_policy is
  'سياسة الجلسات لكل حساب: الحد الأقصى للأجهزة المتصلة وفرضه. enforce=false ⇒ لا يُمنع أي دخول (الافتراضي).';

alter table public.account_session_policy enable row level security;
-- لا سياسات: القراءة والكتابة عبر الدوال المحروسة فقط
revoke all on table public.account_session_policy from anon, authenticated;

-- ② سجل الأحداث الأمنية — أساس المتطلبين ⑦ و⑧
create table if not exists public.security_events (
  id          bigint generated by default as identity primary key,
  user_id     uuid references auth.users (id) on delete set null,
  email       text,
  event       text not null check (event in (
                'login_success', 'login_failed', 'device_conflict', 'limit_exceeded',
                'session_revoked', 'switch_approved', 'switch_denied', 'policy_changed')),
  outcome     text not null default 'info' check (outcome in ('info', 'allowed', 'blocked')),
  session_id  uuid,
  source_hash text,                    -- بصمة الجهاز بعد HMAC (لا يُخزَّن المعرّف الخام)
  ip          inet,
  user_agent  text,
  country     text,                    -- تُملأ في الجولة ٤ فقط — لا ندّعي دقة الموقع
  city        text,
  detail      jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now()
);

comment on table public.security_events is
  'سجل أحداث الدخول والجلسات. يُكتب من staff-login (service_role) ومن دوال السياسة. لا يُحذف.';

alter table public.security_events enable row level security;
revoke all on table public.security_events from anon, authenticated;

create index if not exists idx_security_events_user_time on public.security_events (user_id, created_at desc);
create index if not exists idx_security_events_time      on public.security_events (created_at desc);
create index if not exists idx_security_events_event     on public.security_events (event, created_at desc);

-- ③ الدوال الداخلية

-- سياسة حساب (بالقيم الافتراضية عند غياب الصف): جهاز واحد، غير مفروضة
create or replace function app.session_policy_for(p_user uuid) returns jsonb
language sql stable security definer set search_path = public, app as $$
  select jsonb_build_object(
    'user_id',      p_user,
    'max_sessions', coalesce(p.max_sessions, 1),
    'enforce',      coalesce(p.enforce, false),
    'mode',         case when coalesce(p.max_sessions, 1) = 1 then 'single' else 'multi' end,
    'note',         p.note,
    'updated_at',   p.updated_at
  )
  from (select 1) as anchor
  left join public.account_session_policy p on p.user_id = p_user
$$;
revoke all on function app.session_policy_for(uuid) from public, anon, authenticated;

-- عدد الجلسات النشطة فعلياً (GoTrue). 0 إن لم يوجد جدول الجلسات في بيئة الاختبار المحلي.
create or replace function app.session_active_count(p_user uuid) returns int
language plpgsql stable security definer set search_path = public, app as $$
begin
  if p_user is null or to_regclass('auth.sessions') is null then
    return 0;
  end if;
  return (select count(*)::int from auth.sessions s where s.user_id = p_user);
end $$;
revoke all on function app.session_active_count(uuid) from public, anon, authenticated;

-- تسجيل حدث أمني (لا يرفع استثناءً على المدخلات الطويلة — يقصّها)
create or replace function app.security_event(
  p_event       text,
  p_outcome     text default 'info',
  p_user        uuid default null,
  p_email       text default null,
  p_session_id  uuid default null,
  p_source_hash text default null,
  p_ip          inet default null,
  p_user_agent  text default null,
  p_detail      jsonb default '{}'::jsonb
) returns bigint
language plpgsql security definer set search_path = public, app as $$
declare v_id bigint;
begin
  insert into public.security_events
    (event, outcome, user_id, email, session_id, source_hash, ip, user_agent, detail)
  values
    (p_event, coalesce(p_outcome, 'info'), p_user,
     nullif(left(lower(btrim(coalesce(p_email, ''))), 254), ''),
     p_session_id, p_source_hash, p_ip,
     left(p_user_agent, 400), coalesce(p_detail, '{}'::jsonb))
  returning id into v_id;
  return v_id;
end $$;
revoke all on function app.security_event(text, text, uuid, text, uuid, text, inet, text, jsonb) from public, anon, authenticated;

-- الحاوية الوحيدة المتاحة لخدمة الحافة (service_role) — staff-login
create or replace function public.security_event_record(
  p_event       text,
  p_outcome     text default 'info',
  p_user        uuid default null,
  p_email       text default null,
  p_session_id  uuid default null,
  p_source_hash text default null,
  p_ip          inet default null,
  p_user_agent  text default null,
  p_detail      jsonb default '{}'::jsonb
) returns bigint
language sql security definer set search_path = public, app as $$
  select app.security_event(p_event, p_outcome, p_user, p_email, p_session_id, p_source_hash, p_ip, p_user_agent, p_detail)
$$;
revoke all on function public.security_event_record(text, text, uuid, text, uuid, text, inet, text, jsonb) from public, anon, authenticated;
grant execute on function public.security_event_record(text, text, uuid, text, uuid, text, inet, text, jsonb) to service_role;

-- ④ دوال بوابة تقنية المعلومات (حراسة خادمية بدور it_admin — مؤقتاً حتى الجولة ٣)

-- حارس موحّد: تقنية المعلومات فقط
create or replace function app.require_it_admin(p_action text) returns void
language plpgsql stable security definer set search_path = public, app as $$
begin
  if auth.uid() is null or not app.has_role(array['it_admin']) then
    raise exception 'PERMISSION_DENIED' using detail = 'it.security.sessions:' || p_action;
  end if;
end $$;
revoke all on function app.require_it_admin(text) from public, anon, authenticated;

create or replace function public.session_policy_get(p_user uuid) returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
begin
  perform app.require_it_admin('view');
  return app.session_policy_for(p_user);
end $$;
revoke all on function public.session_policy_get(uuid) from public, anon;
grant execute on function public.session_policy_get(uuid) to authenticated;

create or replace function public.session_policy_set(
  p_user         uuid,
  p_max_sessions int,
  p_enforce      boolean,
  p_note         text default null
) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare v_prev jsonb;
begin
  perform app.require_it_admin('edit');
  if p_user is null then
    raise exception 'INVALID_INPUT' using detail = 'p_user مطلوب';
  end if;
  if p_max_sessions is null or p_max_sessions < 1 or p_max_sessions > 10 then
    raise exception 'INVALID_INPUT' using detail = 'max_sessions يجب أن يكون بين 1 و10';
  end if;
  if p_note is not null and char_length(p_note) > 500 then
    raise exception 'INVALID_INPUT' using detail = 'note أطول من 500 حرف';
  end if;
  if not exists (select 1 from auth.users u where u.id = p_user) then
    raise exception 'USER_NOT_FOUND' using detail = p_user::text;
  end if;

  v_prev := app.session_policy_for(p_user);

  insert into public.account_session_policy (user_id, max_sessions, enforce, note, updated_by, updated_at)
  values (p_user, p_max_sessions, coalesce(p_enforce, false), nullif(btrim(coalesce(p_note, '')), ''), auth.uid(), now())
  on conflict (user_id) do update
     set max_sessions = excluded.max_sessions,
         enforce      = excluded.enforce,
         note         = excluded.note,
         updated_by   = excluded.updated_by,
         updated_at   = now();

  perform app.security_event(
    'policy_changed', 'info', p_user, null, null, null, null, null,
    jsonb_build_object(
      'before_max', v_prev -> 'max_sessions',
      'before_enforce', v_prev -> 'enforce',
      'after_max', p_max_sessions,
      'after_enforce', coalesce(p_enforce, false),
      'by', auth.uid()
    )
  );

  return app.session_policy_for(p_user);
end $$;
revoke all on function public.session_policy_set(uuid, int, boolean, text) from public, anon;
grant execute on function public.session_policy_set(uuid, int, boolean, text) to authenticated;

-- قائمة الحسابات مع سياستها وعدد جلساتها النشطة
create or replace function public.session_policy_list(p_search text default null, p_limit int default 200)
returns table (
  user_id         uuid,
  email           text,
  max_sessions    int,
  enforce         boolean,
  note            text,
  active_sessions int,
  updated_at      timestamptz
)
language plpgsql stable security definer set search_path = public, app as $$
declare v_limit int := greatest(1, least(coalesce(p_limit, 200), 500));
begin
  perform app.require_it_admin('view');
  return query
    select u.id,
           u.email::text,
           coalesce(p.max_sessions, 1),
           coalesce(p.enforce, false),
           p.note,
           app.session_active_count(u.id),
           p.updated_at
    from auth.users u
    left join public.account_session_policy p on p.user_id = u.id
    where nullif(btrim(coalesce(p_search, '')), '') is null
       or u.email ilike '%' || btrim(p_search) || '%'
    order by coalesce(p.enforce, false) desc, u.email
    limit v_limit;
end $$;
revoke all on function public.session_policy_list(text, int) from public, anon;
grant execute on function public.session_policy_list(text, int) to authenticated;

-- سجل الأحداث الأمنية لبوابة تقنية المعلومات
create or replace function public.security_events_list(
  p_user  uuid default null,
  p_event text default null,
  p_limit int  default 200
) returns table (
  id         bigint,
  user_id    uuid,
  email      text,
  event      text,
  outcome    text,
  session_id uuid,
  ip         inet,
  user_agent text,
  country    text,
  city       text,
  detail     jsonb,
  created_at timestamptz
)
language plpgsql stable security definer set search_path = public, app as $$
declare v_limit int := greatest(1, least(coalesce(p_limit, 200), 1000));
begin
  perform app.require_it_admin('view');
  return query
    select e.id, e.user_id, e.email, e.event, e.outcome, e.session_id, e.ip,
           e.user_agent, e.country, e.city, e.detail, e.created_at
    from public.security_events e
    where (p_user is null or e.user_id = p_user)
      and (p_event is null or e.event = p_event)
    order by e.created_at desc, e.id desc
    limit v_limit;
end $$;
revoke all on function public.security_events_list(uuid, text, int) from public, anon;
grant execute on function public.security_events_list(uuid, text, int) to authenticated;

-- ⑤ فحص ذاتي: كل ما أنشأناه موجود، والسياسات معطّلة افتراضياً
do $check$
declare v_cols int;
begin
  if to_regclass('public.account_session_policy') is null or to_regclass('public.security_events') is null then
    raise exception 'SESSION_CORE_CHECK: الجداول لم تُنشأ';
  end if;
  if (select count(*) from public.account_session_policy) <> 0 then
    raise exception 'SESSION_CORE_CHECK: يجب أن تبدأ سياسة الجلسات فارغة (لا فرض على أي حساب)';
  end if;
  if (app.session_policy_for(gen_random_uuid()) ->> 'enforce')::boolean is not false then
    raise exception 'SESSION_CORE_CHECK: الافتراضي يجب أن يكون enforce=false';
  end if;
  select count(*) into v_cols from information_schema.columns
   where table_schema = 'public' and table_name = 'security_events' and column_name in ('ip', 'user_agent', 'country', 'city', 'session_id');
  if v_cols <> 5 then
    raise exception 'SESSION_CORE_CHECK: أعمدة security_events ناقصة (%)', v_cols;
  end if;
end $check$;
