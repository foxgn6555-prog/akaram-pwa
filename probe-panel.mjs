import { chromium } from 'playwright'
const b = await chromium.launch({ args: ['--disable-web-security','--disable-site-isolation-tokrials','--disable-site-isolation-trials'] })
const p = await (await b.newContext({ viewport: { width: 1500, height: 950 } })).newPage()
const calls = []
p.on('response', (r) => { if (r.url().includes('gps_hotspots_details')) calls.push(r.status()) })
const errs = []; p.on('console', m => { if (m.type() === 'error') errs.push(m.text().slice(0, 140)) })
await p.goto('http://127.0.0.1:5173/login', { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(1500)
await p.fill('input[type="email"]','admin@akram.iq'); await p.fill('input[type="password"]','123456789k')
await p.click('button[type="submit"]'); await p.waitForTimeout(6000)
await p.goto('http://127.0.0.1:5173/ops-room/waste-map', { waitUntil: 'domcontentloaded' })
await p.waitForSelector('[data-testid="waste-list-1"], [data-testid^="waste-list-"]', { timeout: 60000 })
await p.waitForTimeout(1500)
const row = p.locator('[data-testid^="waste-list-"]').first()
await row.click(); await p.waitForTimeout(3500)
const panel = await p.locator('[data-testid="hotspot-panel"]').count()
const veh = await p.locator('[data-testid="hotspot-vehicles"]').innerText().catch(() => '')
const hours = await p.locator('[data-testid="hotspot-hours"] > *').count().catch(() => 0)
const days = await p.locator('[data-testid="hotspot-days"] > *').count().catch(() => 0)
console.log(JSON.stringify({ panel, detailsCalls: calls, vehiclesRows: veh.split('\n').length, vehSample: veh.slice(0, 80), hourBars: hours, dayChips: days, errors: errs.slice(0, 3) }, null, 1))
await p.screenshot({ path: '/home/user/shots/waste-panel-details.png' })
await b.close()
