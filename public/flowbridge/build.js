/* ================================================================
   FlowBridge · Build
   -----------------------------------------------------------------
   1) assets/flowbridge-bundle.js  — classic (non-module) bundle of
      the whole app. Loaded by index.html & page.html with a plain
      <script> tag → works in ANY context, including sandboxed
      iframes/previews that block ES modules (CORS/opaque origin).
   2) flowbridge-standalone.html   — FULL app in ONE file
      (all CSS + all JS inline) at the project root.
   The modular source in js/ stays authoritative for development &
   bundler-based integration (esbuild / Vite / Rollup).
   Run: node build.js
   ================================================================ */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const write = (p, c) => { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, c); };

/* ---- strip bare import/export statements from module code ---- */
function stripModule(src) {
  return src
    .replace(/^import\s[^\n]+from\s[^\n]+;\s*$/gm, '')
    .replace(/^\s*export\s+(async\s+)?(function|const|let|var|class)\s/gm, '$1$2 ')
    .replace(/^\s*export\s*\{[\s\S]*?\};\s*$/gm, '');
}

const MODULES = [
  'core/utils.js',
  'core/bus.js',
  'core/defaults.js',
  'core/store.js',
  'engine/engine.js',
  'pages/pagekit.js',
  'pages/dashboard.js',
  'pages/designer.js',
  'pages/portals.js',
  'pages/flows.js',
  'pages/settings.js',
  'main.js'
];

const sources = MODULES.map(f => stripModule(read(path.join('js', f))));
let jsBody = sources.join('\n\n/* ---- module: ---- */\n\n');

/* sanitize for INLINE embedding: an HTML parser terminates a
   <script> element at "<script" / "</script" sequences even when
   they appear inside JS strings or comments. Escape them so the
   single-file build survives (values stay identical at runtime). */
jsBody = jsBody
  .replace(/<\/script/gi, '<\\/script')
  .replace(/<script/gi, '<scr\\u0069pt');

/* ---------- 1) classic bundle ---------- */
const bundle = '/* FlowBridge v2 classic bundle — generated by build.js (do not edit) */\n' +
  '(function () {\n\'use strict\';\n' + jsBody + '\n})();\n';
write(path.join(ROOT, 'assets', 'flowbridge-bundle.js'), bundle);
console.log('✓ assets/flowbridge-bundle.js (' + Math.round(bundle.length / 1024) + ' KB)');

/* ---------- 2) standalone single file (full app) ---------- */
const css = ['tokens.css', 'app.css', 'engine.css']
  .map(f => read(path.join('assets/css', f)))
  .join('\n\n');

const html = `<!DOCTYPE html>
<html lang="ar" dir="rtl">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>FlowBridge — منصة الربط الذكية</title>
<meta name="color-scheme" content="dark">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Tajawal:wght@400;500;700&family=JetBrains+Mono:wght@400;500&display=swap" rel="stylesheet">
<style>
/*__CSS__*/
html,body{height:100%;margin:0}
</style>
</head>
<body>
<div class="fb-shell">
  <header class="fb-topbar" id="topbar"></header>
  <main class="fb-view" id="view"></main>
</div>
<script>
/*__JS__*/
</script>
</body>
</html>`;

const out = html
  .replace('/*__CSS__*/', () => css)
  .replace('/*__JS__*/', () => jsBody);

write(path.join(ROOT, 'flowbridge-standalone.html'), out);
console.log('✓ flowbridge-standalone.html (' + Math.round(out.length / 1024) + ' KB) — full app, single file');
